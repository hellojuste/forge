"""Shared helpers for tools/kit/* (stdlib only).

Earned by: the kit tools each needed the same git runner, the same GENERATED
declaration test and the same census reader; three copies would drift (one
owner, LL-07). Every kit tool imports this module by path.

Exit-code convention for every kit tool: 0 clean, 1 a violation or drift,
2 unreadable input, usage error or a git failure (a failed read is never an
empty read).
"""
import json
import os
import re
import shutil
import subprocess
import sys

KIT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT_GUESS = os.path.dirname(os.path.dirname(KIT_DIR))

# CANON:gen_decl  (owner: tools/map/_common.py GEN_DECL; kept equal by the `canon` check)
GEN_DECL = re.compile(r'GENERATED by \S+|GENERATED\W+(?:do not edit|never hand-edit|regenerat)|"_generated_by"\s*:', re.I)


def declares_generated(text):
    return any(GEN_DECL.search(l) for l in text.splitlines()[:3])


def dump_json(obj):
    return json.dumps(obj, indent=1, sort_keys=True, ensure_ascii=False) + "\n"


def write_json(path, obj):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(dump_json(obj))


def read_json(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def headline(name, n, m, d):
    return "%s: %d violation(s) · %d worklist · denominator %d" % (name, n, m, d)


class KitError(Exception):
    """A failure that maps to exit 2 (unreadable input / git failure)."""


def run(cmd, cwd=None, check=True, input_bytes=None, env=None, capture=True):
    """Run argv; return CompletedProcess with text stdout/stderr."""
    p = subprocess.run(cmd, cwd=cwd, input=input_bytes, env=env,
                       stdout=subprocess.PIPE if capture else None,
                       stderr=subprocess.PIPE if capture else None)
    out = p.stdout.decode("utf-8", "replace") if capture and p.stdout is not None else ""
    err = p.stderr.decode("utf-8", "replace") if capture and p.stderr is not None else ""
    p.out, p.err = out, err
    if check and p.returncode != 0:
        raise KitError("command failed (%d): %s\n%s%s" % (p.returncode, " ".join(cmd), out, err))
    return p


def git(repo, *args, check=True, input_bytes=None):
    return run(["git", "-C", repo] + list(args), check=check, input_bytes=input_bytes)


def git_out(repo, *args):
    return git(repo, *args).out.strip()


def clean_git_env():
    """An environment with no GIT_DIR / GIT_INDEX_FILE / GIT_WORK_TREE leaking in."""
    env = dict(os.environ)
    for k in ("GIT_DIR", "GIT_INDEX_FILE", "GIT_WORK_TREE", "GIT_COMMON_DIR"):
        env.pop(k, None)
    return env


def fixture_git_config(repo):
    git(repo, "config", "user.name", "stable-kit")
    git(repo, "config", "user.email", "kit@localhost")
    git(repo, "config", "commit.gpgsign", "false")
    git(repo, "config", "tag.gpgsign", "false")


def stage_paths(repo):
    """Stage new + modified + deleted files BY PATH LIST (never `add -A`)."""
    p = git(repo, "ls-files", "-o", "-m", "-z", "--exclude-standard")
    paths = [x for x in p.out.split("\0") if x]
    if paths:
        # deleted paths need `git rm --cached`; add the existing ones
        exist = [x for x in paths if os.path.lexists(os.path.join(repo, x))]
        gone = [x for x in paths if not os.path.lexists(os.path.join(repo, x))]
        for i in range(0, len(exist), 200):
            git(repo, "add", "--", *exist[i:i + 200])
        for i in range(0, len(gone), 200):
            git(repo, "rm", "--cached", "-q", "--", *gone[i:i + 200])
    return paths


def force_stage_nested_ignored(repo, paths):
    """`git add -f` the copied build files that a NESTED .gitignore drops (a held upstream tree's own
    .gitignore, e.g. AutoHedge's `.env` / `experimental/`, hiring-agent's `resume/*.pdf`): the build overlay
    is the branch's content of record and lane checks (markets lane_tracked) require every held file
    tracked. A file the kit's ROOT .gitignore (or .git/info/exclude, or a global excludes file) drops
    stays out: those are runtime dirs. Negated matches (`!pattern`) are not ignores. Returns the forced
    paths."""
    paths = [x for x in paths if x]
    if not paths:
        return []
    p = git(repo, "check-ignore", "-v", "-z", "--stdin", check=False,
            input_bytes=("\0".join(paths) + "\0").encode("utf-8"))
    if p.returncode not in (0, 1):
        raise KitError("git check-ignore failed (%d): %s" % (p.returncode, p.err))
    f = p.out.split("\0")
    forced = []
    for i in range(0, len(f) - 3, 4):
        src, _line, pat, path = f[i:i + 4]
        if not path or pat.startswith("!"):
            continue
        src = src.replace(os.sep, "/")
        if "/" not in src or src.startswith(".git/") or os.path.isabs(src) or not src.endswith(".gitignore"):
            continue  # root .gitignore / info/exclude / core.excludesFile: the kit's own rule wins
        forced.append(path)
    for i in range(0, len(forced), 200):
        git(repo, "add", "-f", "--", *forced[i:i + 200])
    return forced


def has_staged(repo):
    return git(repo, "diff", "--cached", "--quiet", check=False).returncode != 0


def commit(repo, msg):
    git(repo, "-c", "user.name=stable-kit", "-c", "user.email=kit@localhost",
        "-c", "commit.gpgsign=false", "commit", "-q", "--no-verify", "-m", msg)


def copy_tree(src, dst, skip_names=(".git",)):
    """Copy src/. into dst; returns the list of relative file paths copied.
    Refuses symlinks (exit 2 upstream) - ingest dereferenced them all."""
    copied = []
    for base, dirs, files in os.walk(src):
        dirs[:] = sorted(d for d in dirs if d not in skip_names)
        rel_base = os.path.relpath(base, src)
        for fn in sorted(files):
            s = os.path.join(base, fn)
            rel = os.path.normpath(os.path.join(rel_base, fn))
            if os.path.islink(s):
                raise KitError("symlink in build tree (refused): %s" % s)
            d = os.path.join(dst, rel)
            os.makedirs(os.path.dirname(d), exist_ok=True)
            shutil.copy2(s, d)
            copied.append(rel.replace(os.sep, "/"))
        for dn in dirs:
            if os.path.islink(os.path.join(base, dn)):
                raise KitError("symlinked dir in build tree (refused): %s" % os.path.join(base, dn))
    return copied


def list_files(root, skip=(".git",)):
    out = []
    for base, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if d not in skip]
        for fn in files:
            out.append(os.path.relpath(os.path.join(base, fn), root).replace(os.sep, "/"))
    return sorted(out)


