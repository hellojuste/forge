def _unquote(v):
    v = v.strip()
    if len(v) >= 2 and v[0] == v[-1] == "'":
        return v[1:-1].replace("''", "'")
    if len(v) >= 2 and v[0] == v[-1] == '"':
        try:
            return json.loads(v)
        except ValueError:
            return v[1:-1]
    if v in ("null", "~", ""):
        return None
    if v == "true":
        return True
    if v == "false":
        return False
    if re.fullmatch(r"-?\d+", v):
        return int(v)
    return v


def read_census_stdlib(path):
    """Reader for the fixed shape of SKILL_CENSUS.yml: a `skills:` list of
    `- id:` blocks with two-space scalar keys, folded continuation lines
    (indent >= 4) and two-space `- item` lists. Returns list of dicts."""
    rows, cur, key, in_skills = [], None, None, False
    with open(path, encoding="utf-8") as f:
        for raw in f:
            line = raw.rstrip("\n")
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            if not line.startswith(" ") and not line.startswith("-"):
                in_skills = line.startswith("skills:")
                continue
            if not in_skills:
                continue
            if line.startswith("- "):
                cur = {}
                rows.append(cur)
                k, _, v = line[2:].partition(":")
                key = k.strip()
                cur[key] = _unquote(v)
                continue
            if cur is None:
                continue
            if line.startswith("  - "):
                if not isinstance(cur.get(key), list):
                    cur[key] = []
                cur[key].append(_unquote(line[4:]))
                continue
            if line.startswith("    "):  # folded continuation of the previous scalar
                prev = cur.get(key)
                if isinstance(prev, str):
                    # re-read the raw quoted form: append then unquote lazily
                    cur[key] = (prev + " " + line.strip()).strip()
                continue
            m = re.match(r"  ([A-Za-z_][\w-]*):(.*)$", line)
            if m:
                key = m.group(1)
                val = m.group(2)
                if val.strip() == "":
                    cur[key] = None
                elif val.strip().startswith("'") and not val.strip().endswith("'") or \
                        (val.strip().startswith("'") and val.strip() == "'"):
                    cur[key] = val.strip()  # multi-line single-quoted; closed later
                else:
                    cur[key] = _unquote(val)
    # close multi-line single-quoted scalars
    for r in rows:
        for k, v in list(r.items()):
            if isinstance(v, str) and v.startswith("'") and v.endswith("'") and len(v) > 1:
                r[k] = v[1:-1].replace("''", "'")
    return rows


def load_census(path, root=None):
    """Prefer commons' tools/upstream/skill_routes.load_census when present
    (one owner); fall back to the stdlib reader of the fixed shape.
    Returns (rows, reader_name)."""
    cand = []
    if root:
        cand.append(os.path.join(root, "tools", "upstream"))
    cand.append(os.path.join(REPO_ROOT_GUESS, "tools", "upstream"))
    for d in cand:
        p = os.path.join(d, "skill_routes.py")
        if os.path.isfile(p):
            try:
                import importlib.util
                spec = importlib.util.spec_from_file_location("_kit_skill_routes", p)
                mod = importlib.util.module_from_spec(spec)
                spec.loader.exec_module(mod)
                if hasattr(mod, "load_census"):
                    rows = mod.load_census(path)
                    if isinstance(rows, dict):
                        rows = rows.get("skills", [])
                    if rows and isinstance(rows[0], dict) and "id" in rows[0]:
                        return rows, "skill_routes.load_census"
            except Exception:  # fall through to our reader; recorded by name
                pass
    return read_census_stdlib(path), "tools/kit/_kit.read_census_stdlib"


def stations_from_tree(root):
    """Station names in decision-tree order, from router/kit_tree.json."""
    p = os.path.join(root, "router", "kit_tree.json")
    d = read_json(p)
    rows = d["intents"] if isinstance(d, dict) else d
    out = []
    for r in rows:
        n = r.get("name", "")
        if n.startswith("station:"):
            out.append(n.split(":", 1)[1])
    return out


def die(msg, code=2):
    sys.stderr.write(msg.rstrip() + "\n")
    sys.exit(code)
