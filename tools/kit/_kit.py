def stage_paths(repo):
    """Stage new + modified + deleted files BY PATH LIST (never `add -A`)."""
    p = git(repo, "ls-files", "-o", "-m", "-z", "--exclude-standard")
    paths = [x for x in p.out.split("\0") if x]
    if paths:
        # deleted paths need `git rm --cached`; add the existing ones
        exist = [x for x in paths if os.path.lexists(os.path.join(repo, x))]
        gone = [x for x in paths if not os.path.lexists(os.path.join(repo, x))]
        for i in range(0, len(exist), 200):
            git(repo, "add", "--", *exist[i:i + 200])
        for i in range(0, len(gone), 200):
            git(repo, "rm", "--cached", "-q", "--", *gone[i:i + 200])
    return paths


def force_stage_nested_ignored(repo, paths):
    """`git add -f` the copied build files that a NESTED .gitignore drops (a held upstream tree's own
    .gitignore, e.g. AutoHedge's `.env` / `experimental/`, hiring-agent's `resume/*.pdf`): the build overlay
    is the branch's content of record and lane checks (markets lane_tracked) require every held file
    tracked. A file the kit's ROOT .gitignore (or .git/info/exclude, or a global excludes file) drops
    stays out: those are runtime dirs. Negated matches (`!pattern`) are not ignores. Returns the forced
    paths."""
    paths = [x for x in paths if x]
    if not paths:
        return []
    p = git(repo, "check-ignore", "-v", "-z", "--stdin", check=False,
            input_bytes=("\0".join(paths) + "\0").encode("utf-8"))
    if p.returncode not in (0, 1):
        raise KitError("git check-ignore failed (%d): %s" % (p.returncode, p.err))
    f = p.out.split("\0")
    forced = []
    for i in range(0, len(f) - 3, 4):
        src, _line, pat, path = f[i:i + 4]
        if not path or pat.startswith("!"):
            continue
        src = src.replace(os.sep, "/")
        if "/" not in src or src.startswith(".git/") or os.path.isabs(src) or not src.endswith(".gitignore"):
            continue  # root .gitignore / info/exclude / core.excludesFile: the kit's own rule wins
        forced.append(path)
    for i in range(0, len(forced), 200):
        git(repo, "add", "-f", "--", *forced[i:i + 200])
    return forced


def has_staged(repo):
    return git(repo, "diff", "--cached", "--quiet", check=False).returncode != 0


