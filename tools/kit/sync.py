#!/usr/bin/env python3
"""sync.py - bring main's commons into the current station branch.

Earned by: two programmes regenerated the same files from different inputs and
each merge left one stale (LL-24 "rebuild after combining"); and a station that
edits a commons file turns every later merge into a hand-resolution (KIT_PLAN
3.3 branch discipline). Retires: hand `git merge main` on stations.

  sync.py [--root R] [--main <ref>] [--no-audit]
      --main defaults to the kit's resolved main (tools/kit/_kit.main_ref: local main, local
      claude/stable-kit-main, then origin/main or origin/claude/stable-kit-main - REPRODUCE F2).
      on a station branch: `git merge --no-ff main`. On conflict, for each
      conflicted path:
        * GENERATED (its first 3 lines declare it):
            main-owned generated files (commons/MANIFEST.json, SKILLS_INDEX.md,
            registry/skill_assignment.json, registry/skills_index.json,
            map/STATIONS.md) take main's side - a station never regenerates them;
            every other generated file takes ours, is REGENERATED by its tool,
            and is added;
        * anything else -> `git merge --abort`, print the paths, exit 1 (a
          branch-discipline violation: move that edit to main or to a
          station-only fragment).
      Then `python3 tools/station_audit.py --changed` (exit 1 if it fails).
      Never rebases, never forces.
  sync.py --check     dry run with `git merge-tree --write-tree` (no ref moves)
  sync.py --selftest
Exit 0 clean/merged · 1 violation (non-generated conflict, audit red) · 2 usage/git failure.
"""
import os
import re
import shutil
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _kit  # noqa: E402

MAIN_OWNED_GENERATED = {
    "commons/MANIFEST.json", "SKILLS_INDEX.md", "registry/skill_assignment.json",
    "registry/skills_index.json", "map/STATIONS.md",
}

# (path regex, argv) - the regenerators; each runs once per sync if its script exists.
REGEN = [
    (r"^governance/OWNERSHIP\.md$", ["tools/gov/gen_ownership.py", "--write"]),
    (r"^map/(SOLUTIONS\.md|usage\.json|atlas\.json|ATLAS\.md)$", ["tools/map/map_check.py", "--write"]),
    (r"(^|/)README\.md$", ["tools/map/map_check.py", "--write"]),
    (r"^brain/INDEX\.md$", ["tools/brain.py", "index"]),
    (r"^NOTICE\.md$", ["tools/upstream/notice.py", "--root", ".", "--write"]),
    (r"^repertoire/INDEX\.md$", ["tools/upstream/skill_routes.py", "index", "--station-root", "."]),
]
GEN_TOOL = re.compile(r"GENERATED by (\S+?\.py)\b|\"_generated_by\"\s*:\s*\"([^\"]+?\.py)\"")


def current_branch(root):
    p = _kit.git(root, "symbolic-ref", "--short", "-q", "HEAD", check=False)
    return p.out.strip() if p.returncode == 0 else None


def blob(root, spec):
    p = _kit.git(root, "show", spec, check=False)
    return p.out if p.returncode == 0 else None


def is_generated_text(txt):
    return txt is not None and _kit.declares_generated(txt)


def regen_cmds_for(path, text):
    cmds = []
    for rx, argv in REGEN:
        if re.search(rx, path):
            cmds.append(argv)
    if not cmds and text:
        for line in text.splitlines()[:3]:
            m = GEN_TOOL.search(line)
            if m:
                tool = m.group(1) or m.group(2)
                cmds.append([tool, "--write"])
                break
    return cmds


def classify_conflicts(root, paths, ref_ours, ref_theirs, staged=True):
    gen, other = [], []
    for p in paths:
        if staged:
            o, t = blob(root, ":2:" + p), blob(root, ":3:" + p)
        else:
            o, t = blob(root, "%s:%s" % (ref_ours, p)), blob(root, "%s:%s" % (ref_theirs, p))
        if is_generated_text(o) or is_generated_text(t):
            gen.append((p, o, t))
        else:
            other.append(p)
    return gen, other


def run_regen(root, cmds):
    done, failed = [], []
    seen = set()
    for argv in cmds:
        key = tuple(argv)
        if key in seen:
            continue
        seen.add(key)
        script = os.path.join(root, argv[0])
        if not os.path.isfile(script):
            failed.append("%s (script absent)" % " ".join(argv))
            continue
        p = _kit.run([sys.executable] + argv, cwd=root, check=False)
        (done if p.returncode == 0 else failed).append(" ".join(argv) + ("" if p.returncode == 0 else " -> exit %d" % p.returncode))
    return done, failed


LANES = ("repertoire/", "upstream/", "study/", "nc-lane/", ".upstream/", ".git/")


def regen_all(root, on_station):
    """Regenerate every GENERATED file in the tree once: the REGEN table first,
    then the tool each remaining file declares (`GENERATED by tools/<x>.py` ->
    `python3 tools/<x>.py --write`). Main-owned generated files are skipped
    (assemble/main handle them explicitly). Upstream lanes are never scanned
    (an upstream file that says "GENERATED by protoc" is data)."""
    cmds = []
    for rel in _kit.list_files(root, skip=(".git", ".upstream", "__pycache__")):
        if rel in MAIN_OWNED_GENERATED:
            continue
        if rel.startswith(LANES) and rel != "repertoire/INDEX.md":
            continue
        try:
            with open(os.path.join(root, rel), encoding="utf-8", errors="replace") as f:
                head = "".join(f.readline() for _ in range(3))
        except OSError:
            continue
        if not _kit.declares_generated(head):
            continue
        for argv in regen_cmds_for(rel, head):
            if argv[0].startswith("tools/") and argv not in cmds:
                cmds.append(argv)
    return run_regen(root, cmds)


def do_check(root, main_ref):
    br = current_branch(root)
    p = _kit.git(root, "merge-tree", "--write-tree", "--name-only", "--no-messages", "HEAD", main_ref, check=False)
    if p.returncode == 0:
        print("sync --check: %s <- %s merges cleanly" % (br, main_ref))
        return 0
    if p.returncode != 1:
        print("sync --check: git merge-tree failed: %s" % p.err.strip())
        return 2
    lines = [x for x in p.out.splitlines()[1:] if x.strip()]
    gen, other = classify_conflicts(root, lines, "HEAD", main_ref, staged=False)
    print("sync --check: %d conflicted path(s): %d GENERATED (regenerated on sync) · %d other"
          % (len(lines), len(gen), len(other)))
    for g in gen:
        print("  GENERATED %s" % g[0])
    for o in other:
        print("  VIOLATION %s (a station edited a commons path)" % o)
    return 1 if other else 0


def do_sync(root, main_ref, audit=True):
    br = current_branch(root)
    if not br:
        print("sync: detached HEAD; check out a station branch first")
        return 2
    if br == main_ref or br in ("main", _kit.HOSTED_PREFIX + "main"):
        print("sync: on %s; run sync on a station branch" % main_ref)
        return 2
    if _kit.git(root, "diff", "--quiet", "HEAD", check=False).returncode != 0:
        print("sync: uncommitted changes to tracked files; commit or stash them first")
        return 2
    m = _kit.git(root, "-c", "user.name=stable-kit", "-c", "user.email=kit@localhost", "-c", "commit.gpgsign=false",
                 "merge", "--no-ff", "--no-edit", "-m", "sync: merge %s into %s" % (main_ref, br), main_ref, check=False)
    if m.returncode == 0:
        print("sync: %s <- %s merged (%s)" % (br, main_ref, (m.out.strip().splitlines() or ["ok"])[-1]))
        return _audit(root, audit)
    conflicted = [x for x in _kit.git(root, "diff", "--name-only", "--diff-filter=U", check=False).out.splitlines() if x]
    if not conflicted:
        print("sync: merge failed without conflicts: %s" % (m.err.strip() or m.out.strip()))
        _kit.git(root, "merge", "--abort", check=False)
        return 2
    gen, other = classify_conflicts(root, conflicted, None, None, staged=True)
    if other:
        _kit.git(root, "merge", "--abort", check=False)
        print("sync: ABORTED - %d conflict(s) outside GENERATED files (branch-discipline violation):" % len(other))
        for o in other:
            print("  %s" % o)
        print("  fix: a station never edits a commons file; move the edit to main or a station-only fragment, then sync again")
        return 1
    cmds = []
    for path, ours, theirs in gen:
        if path in MAIN_OWNED_GENERATED:
            side = "--theirs" if theirs is not None else "--ours"
        else:
            side = "--ours" if ours is not None else "--theirs"
        _kit.git(root, "checkout", side, "--", path)
        if path not in MAIN_OWNED_GENERATED:
            cmds += regen_cmds_for(path, ours or theirs)
    # REGENERATE: the step that makes a GENERATED conflict resolve to the truth of the merged tree
    done, failed = run_regen(root, cmds)
    for path, _, _ in gen:
        if os.path.exists(os.path.join(root, path)):
            _kit.git(root, "add", "--", path)
    # files a regenerator rewrote beyond the conflicted ones
    mod = [x for x in _kit.git(root, "diff", "--name-only").out.splitlines() if x]
    gen_mod = [x for x in mod if is_generated_text(open(os.path.join(root, x), encoding="utf-8", errors="replace").read())]
    if gen_mod:
        _kit.git(root, "add", "--", *gen_mod)
    left = [x for x in _kit.git(root, "diff", "--name-only", "--diff-filter=U", check=False).out.splitlines() if x]
    if left or failed:
        _kit.git(root, "merge", "--abort", check=False)
        print("sync: ABORTED - regeneration incomplete: unresolved %s; failed %s" % (left, failed))
        return 1
    _kit.git(root, "-c", "user.name=stable-kit", "-c", "user.email=kit@localhost", "-c", "commit.gpgsign=false",
             "commit", "-q", "--no-verify", "--no-edit")
    print("sync: %s <- %s merged; %d GENERATED conflict(s) resolved by regeneration (%s)"
          % (br, main_ref, len(gen), "; ".join(done) or "main-owned side taken"))
    return _audit(root, audit)


def _audit(root, audit):
    if not audit:
        return 0
    sa = os.path.join(root, "tools", "station_audit.py")
    if not os.path.isfile(sa):
        print("sync: tools/station_audit.py absent - audit skipped (WORKLIST)")
        return 0
    p = _kit.run([sys.executable, "tools/station_audit.py", "--changed"], cwd=root, check=False)
    head = (p.out.strip().splitlines() or [""])[0]
    print("sync: station_audit --changed -> exit %d %s" % (p.returncode, head))
    return 0 if p.returncode == 0 else 1


# ------------------------------------------------------------------ selftest
GEN_PY = r'''import os, sys
srcs = sorted(f for f in os.listdir("src") if f.endswith(".txt"))
out = "<!-- GENERATED by tools/gen.py — edit src/*.txt, then run python3 tools/gen.py --write -->\n" + "".join("- %s\n" % s for s in srcs)
if "--check" in sys.argv:
    sys.exit(0 if open("gen/OUT.md").read() == out else 1)
os.makedirs("gen", exist_ok=True)
open("gen/OUT.md", "w").write(out)
'''
AUDIT_PY = r'''import subprocess, sys
sys.exit(subprocess.call([sys.executable, "tools/gen.py", "--check"]))
'''


def build_fixture(tmp):
    repo = os.path.join(tmp, "kit")
    _kit.run(["git", "init", "-q", "-b", "main", repo])
    _kit.fixture_git_config(repo)
    w = lambda rel, txt: (os.makedirs(os.path.dirname(os.path.join(repo, rel)) or repo, exist_ok=True),
                          open(os.path.join(repo, rel), "w").write(txt))
    w("tools/gen.py", GEN_PY)
    w("tools/station_audit.py", AUDIT_PY)
    w("src/a.txt", "a\n")
    w("router/intents.json", '{"intents": ["build"]}\n')
    _kit.run([sys.executable, "tools/gen.py", "--write"], cwd=repo)
    _kit.stage_paths(repo)
    _kit.commit(repo, "main: commons")
    return repo, w


def _selftest():
    tmp = tempfile.mkdtemp(prefix="kit-sync-")
    try:
        repo, w = build_fixture(tmp)
        g = lambda *a: _kit.git(repo, *a)
        g("switch", "-q", "-c", "station/alpha", "main")
        w("src/station.txt", "s\n")
        _kit.run([sys.executable, "tools/gen.py", "--write"], cwd=repo)
        _kit.stage_paths(repo)
        _kit.commit(repo, "alpha overlay")
        g("switch", "-q", "-c", "station/beta", "main")
        w("router/intents.json", '{"intents": ["build", "beta-edit"]}\n')   # discipline violation
        _kit.stage_paths(repo)
        _kit.commit(repo, "beta edits a commons file")
        g("switch", "-q", "main")
        w("src/main2.txt", "m\n")
        w("router/intents.json", '{"intents": ["build", "main-edit"]}\n')
        _kit.run([sys.executable, "tools/gen.py", "--write"], cwd=repo)
        _kit.stage_paths(repo)
        _kit.commit(repo, "main: commons release 2")

        # case 1: GENERATED conflict -> regenerated, merged, audit green
        g("switch", "-q", "station/alpha")
        assert do_check(repo, "main") == 0, "dry run: generated-only conflict is resolvable"
        head0 = _kit.git_out(repo, "rev-parse", "HEAD")
        assert do_sync(repo, "main") == 0, "generated conflict must resolve"
        out = open(os.path.join(repo, "gen/OUT.md")).read()
        assert "- main2.txt" in out and "- station.txt" in out and "- a.txt" in out, \
            "regenerated file must reflect the merged tree, got:\n" + out
        assert _kit.git(repo, "merge-base", "--is-ancestor", "main", "HEAD", check=False).returncode == 0
        assert _kit.git_out(repo, "rev-parse", "HEAD^1") == head0, "a merge commit, not a rebase"
        assert do_sync(repo, "main") == 0, "second sync is a no-op"
        assert main(["--root", repo, "--check"]) == 0, "default --main resolves to main"
        # REPRODUCE F2: hosted naming - a station worktree on claude/stable-kit-alpha syncs from claude/stable-kit-main
        hosted = _kit.fixture_layouts(repo, tmp)["hosted"]
        _kit.git(hosted, "switch", "-q", "-c", "claude/stable-kit-alpha", "origin/claude/stable-kit-alpha")
        assert _kit.main_ref(hosted) == "refs/heads/claude/stable-kit-main", _kit.main_ref(hosted)
        assert main(["--root", hosted, "--check"]) == 0, "hosted layout: --check against the resolved main"
        _kit.git(hosted, "switch", "-q", "claude/stable-kit-main")
        assert main(["--root", hosted, "--no-audit"]) == 2, "hosted main itself is refused"

        # case 2: commons conflict -> abort, branch unchanged
        g("switch", "-q", "station/beta")
        assert do_check(repo, "main") == 1, "dry run must flag the commons conflict"
        before = _kit.git_out(repo, "rev-parse", "HEAD")
        assert do_sync(repo, "main") == 1, "commons conflict must abort"
        assert _kit.git_out(repo, "rev-parse", "HEAD") == before, "branch must be unchanged"
        assert not os.path.exists(os.path.join(repo, ".git", "MERGE_HEAD")), "merge must be aborted"

        # case 3: refusals
        g("switch", "-q", "main")
        assert do_sync(repo, "main") == 2, "refuse on main"
        print("selftest OK")
        return 0
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    if "--selftest" in argv:
        return _selftest()
    root = os.getcwd()
    main_ref = None
    if "--root" in argv:
        root = argv[argv.index("--root") + 1]
    if "--main" in argv:
        main_ref = argv[argv.index("--main") + 1]
    p = _kit.git(root, "rev-parse", "--show-toplevel", check=False)
    if p.returncode != 0:
        print("sync: not a git repo: %s" % root)
        return 2
    root = p.out.strip()
    if main_ref is None:
        full = _kit.main_ref(root)
        if not full:
            print("sync: no main ref (main, claude/stable-kit-main, local or remote-tracking); pass --main <ref>")
            return 2
        main_ref = re.sub(r"^refs/(heads|remotes)/", "", full)
    try:
        if "--check" in argv:
            return do_check(root, main_ref)
        return do_sync(root, main_ref, audit="--no-audit" not in argv)
    except _kit.KitError as e:
        print("sync: git failure: %s" % e)
        return 2


if __name__ == "__main__":
    sys.exit(main())
