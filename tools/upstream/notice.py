#!/usr/bin/env python3
"""notice.py — NOTICE.md for a station, GENERATED from upstream/LOCK.json + PROVENANCE.json + the carried NOTICE files.

Earned by: LEAN LL-08 ("kept verbatim, attributed") and LL-09 (licence decided before ingest): Apache-2.0 §4(d)
requires the NOTICE text to travel with the work (impeccable NOTICE.md, Vibe-Trading NOTICE, evo NOTICE, ARS
NOTICE.md, REA THIRD_PARTY_NOTICES.md), and every held tree must say where it came from, at which 40-hex pin, under
which licence. A hand-kept attribution file drifts from the rows the moment a second ingest runs; this one is
re-rendered, and `--check` fails when it is stale (a generated file in git is a claim).

CLI: notice.py --root <station root> --write | --check      (default --check)
     notice.py --selftest
Exit: 0 written / fresh · 1 stale or missing · 2 unreadable rows.
"""
import argparse
import contextlib
import io
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _uplib as U  # noqa: E402

TOOL = "tools/upstream/notice.py"


def render(root):
    root = Path(root)
    lock = U.rows_of(U.load_json(root / "upstream" / "LOCK.json", None))
    prov = U.rows_of(U.load_json(root / "upstream" / "PROVENANCE.json", None))
    by_tree = {}
    for r in prov:
        t = U.tree_of(r.get("path", "")) or "(outside a held tree)"
        by_tree.setdefault(t, []).append(r)
    out = ["<!-- GENERATED by %s -- do not edit; regenerate: python3 %s --root . --write -->" % (TOOL, TOOL),
           "# NOTICE",
           "",
           "This station holds third-party material at pinned commits. Each component below keeps its own licence file",
           "beside it; nothing here relicenses it. Held trees are read-only data (see `upstream/PRECEDENCE.json`);",
           "bootstrap components are NOT in this repository: `tools/kit/bootstrap.py` fetches them at the pin into the",
           "gitignored `.upstream/` cache.",
           ""]
    if not lock:
        out += ["No upstream component is held by this branch.", ""]
    out += ["## Components", "", "| # | repository | pin (40-hex) | how | held at | licence | files |", "|---|---|---|---|---|---|---|"]
    for r in sorted(lock, key=lambda x: (x.get("repo_id") or 0, x.get("repo", ""), x.get("how", ""), x.get("lane") or "")):
        held = r.get("held_root") or ""
        nfiles = len(by_tree.get(held, [])) if r.get("held") != "bootstrap" else 0
        how = r.get("how", "")
        if r.get("copy_of"):
            how += " (copy of station %s)" % r["copy_of"]
        out.append("| %s | [%s](https://github.com/%s) | `%s` | %s | `%s` | %s | %s |" % (
            r.get("repo_id") or "", r.get("repo"), r.get("repo"), r.get("sha"), how,
            held if r.get("held") != "bootstrap" else ".upstream/ (bootstrap, not committed)",
            str(r.get("licence", "UNKNOWN")).replace("|", "/"), nfiles if r.get("held") != "bootstrap" else "-"))
    out.append("")
    lic_rows = [p for p in prov if p.get("role") == "licence"]
    if lic_rows:
        out += ["## Licence files held", ""]
        for p in sorted(lic_rows, key=lambda x: x["path"]):
            t = (root / p["path"])
            cls = U.classify_licence(t.read_text(encoding="utf-8", errors="replace")) if t.is_file() else "MISSING"
            out.append("- `%s` — %s (from `%s` @ `%s`)" % (p["path"], cls, p.get("source_path"), (p.get("sha") or "")[:12]))
        out.append("")
    ren = [p for p in prov if p.get("renamed_from")]
    syml = [p for p in prov if p.get("symlink_from")]
    if ren or syml:
        out += ["## Changes made at ingest", "",
                "The bytes of every held file are unmodified (PROVENANCE.json records each sha256). Only paths changed:", ""]
        if ren:
            out.append("- %d agent file path(s) neutralised so no harness auto-loads them (`.claude/` -> `_upstream_claude/`, "
                       "`CLAUDE.md`/`AGENTS.md`/`.mcp.json` -> `_upstream_*`, `hooks/hooks.json` -> `hooks/_upstream_hooks.json`); "
                       "rows in `upstream/RENAMES.json`." % len(ren))
        if syml:
            out.append("- %d symlink(s) replaced by a copy of their target (recorded as `symlink_from`)." % len(syml))
        out.append("")
    notices = [p for p in prov if p.get("role") == "notice"]
    if notices:
        out += ["## Carried notices", "", "Reproduced verbatim from the upstream NOTICE files, as their licences require.", ""]
        for p in sorted(notices, key=lambda x: x["path"]):
            f = root / p["path"]
            text = f.read_text(encoding="utf-8", errors="replace") if f.is_file() else "(file missing: %s)\n" % p["path"]
            fence = "````" if "```" in text else "```"
            out += ["### %s (%s @ `%s`)" % (p["path"], p.get("repo"), (p.get("sha") or "")[:12]), "", fence + "text",
                    text.rstrip("\n"), fence, ""]
    out.append("%d component row(s) · %d held file(s) · %d carried notice(s)" % (len(lock), len(prov), len(notices)))
    return "\n".join(out) + "\n"


def run(root, write):
    root = Path(root)
    text = render(root)
    p = root / "NOTICE.md"
    if write:
        if not p.exists() or p.read_text(encoding="utf-8") != text:
            p.write_text(text, encoding="utf-8")
        print("notice: wrote %s" % p)
        return 0
    lock = U.rows_of(U.load_json(root / "upstream" / "LOCK.json", None))
    if not lock and not p.exists():
        print("notice: 0 violation(s) · 0 worklist · denominator 0")
        return 0
    cur = p.read_text(encoding="utf-8") if p.exists() else None
    viol = [] if cur == text else ["NOTICE.md %s (regenerate: python3 %s --root . --write)" % ("missing" if cur is None else "stale", TOOL)]
    return U.finish("notice", viol, [], len(lock))


def selftest():
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import ingest
    cases = 0
    with tempfile.TemporaryDirectory() as t:
        src, st = Path(t, "src"), Path(t, "st")
        src.mkdir()
        sha = ingest.make_fixture(str(src))
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf), contextlib.redirect_stderr(buf):
            assert ingest.main(["--clone", str(src), "--sha", sha, "--repo", "o/r", "--repo-id", "7", "--lane", "upstream",
                                "--dest", str(st), "--path", ".", "--deref"]) == 0, buf.getvalue()
            assert run(st, write=False) == 1, "missing NOTICE.md is red"
            assert run(st, write=True) == 0
            assert run(st, write=False) == 0, "fresh after write"
        txt = (st / "NOTICE.md").read_text()
        assert U.declares_generated(txt), "GENERATED declaration in the first 3 lines"
        assert "Fixture NOTICE: keep me." in txt and ("`%s`" % sha) in txt and "GPL" in txt, txt
        assert "upstream/o~r/pkg/LICENSE` — MIT" in txt, "nearest licence listed with its class"
        assert "neutralised" in txt and "symlink(s) replaced" in txt
        cases += 5
        (st / "NOTICE.md").write_text(txt.replace("Fixture NOTICE", "Edited NOTICE"))
        with contextlib.redirect_stdout(io.StringIO()):
            assert run(st, write=False) == 1, "hand edit is stale"
        cases += 1
        with contextlib.redirect_stdout(io.StringIO()):
            assert run(Path(t, "empty"), write=False) == 0, "a branch holding nothing is green"
        cases += 1
    print("notice selftest OK (%d cases)" % cases)
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args(argv)
    if a.selftest:
        return selftest()
    try:
        return run(U.find_root(a.root), a.write)
    except (OSError, ValueError) as e:
        print("notice: UNREADABLE %s" % e)
        return 2


if __name__ == "__main__":
    sys.exit(main())
