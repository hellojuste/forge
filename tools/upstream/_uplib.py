def walk_files(root, skip_dirs=(".git", ".upstream", ".cache", ".station", ".usage", "__pycache__", "node_modules")):
    root = Path(root)
    out = []
    for dp, dns, fns in os.walk(root):
        dns[:] = [d for d in dns if d not in skip_dirs]
        for fn in fns:
            full = Path(dp) / fn
            if full.is_symlink():
                out.append(full.relative_to(root).as_posix())
                continue
            out.append(full.relative_to(root).as_posix())
    return sorted(out)


def headline(name, n, m, d):
    return "%s: %d violation(s) · %d worklist · denominator %s" % (name, n, m, d)


def finish(name, violations, worklist, denom, detail_limit=60):
    """Print the headline + details; return exit code 0/1."""
    print(headline(name, len(violations), len(worklist), denom))
    for v in violations[:detail_limit]:
        print("  VIOLATION " + v)
    if len(violations) > detail_limit:
        print("  ... %d more violation(s)" % (len(violations) - detail_limit))
    for w in worklist[:detail_limit]:
        print("  WORKLIST " + w)
    if len(worklist) > detail_limit:
        print("  ... %d more worklist item(s)" % (len(worklist) - detail_limit))
    return 1 if violations else 0


def frontmatter(text):
    """Minimal SKILL.md frontmatter reader: top-level `key: value` lines (folded/quoted values joined)."""
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end < 0:
        return {}
    fm = {}
    key = None
    for line in text[3:end].splitlines():
        if not line.strip():
            continue
        m = re.match(r"^([A-Za-z0-9_-]+):\s*(.*)$", line)
        if m and not line.startswith(" "):
            key = m.group(1)
            val = m.group(2).strip()
            if val in (">", "|", ">-", "|-"):
                val = ""
            fm[key] = val.strip("'\"") if val[:1] in "'\"" and val[-1:] == val[:1] else val
        elif key and line.startswith(" "):
            fm[key] = (fm[key] + " " + line.strip()).strip()
    return fm
