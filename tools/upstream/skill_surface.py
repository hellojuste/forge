#!/usr/bin/env python3
"""skill_surface.py — every canonical skill homed in a station is natively discoverable by Claude Code; only true
duplicates are hidden, through the file Claude Code actually reads. Stdlib only.

Earned by: the operator ruling of 2026-10-16 (DEC-core-0010, verbatim: "its nuts to think there would only use 6
anyway what is the point of doing all this ... ? weird built out") which RETIRED the 6-skill listing cap, and
LEAN review F2 (the listing diet lived in station.json skill_overrides, which Claude Code never reads, so the check
counted what the kit intended, not what the harness listed).

Mechanism (verified against code.claude.com/docs/en/skills.md, 2026-10-16: "a <skill-name> entry in the ... project
location can be a symlink to a directory elsewhere on disk"; the directory name invokes the skill; `skillOverrides`
in settings takes on | name-only | user-invocable-only | off; `skillListingBudgetFraction` sizes the listing at 1% of
the context window by default and overflow drops the least-invoked descriptions, never a name):
  1. SURFACE. Each router/skills.json row of kind canonical (a held copy is the station's canonical instance) whose
     path is a SKILL.md inside a lane (upstream/ repertoire/ study/ nc-lane/) gets a symlink
     `.claude/skills/<surface-name>` -> its skill directory (relative). The lane stays read-only and byte-identical;
     the skill's scripts and references resolve beside it. surface-name = the row name in [a-z0-9-] (<= 64 chars);
     a name already taken (a kit skill, or an earlier row) gets `--<repo>` and then `-2`, `-3` ... appended.
     Mirrors, symlinks, variants and fixtures are NOT surfaced: they route to their canonical (router/skills.json).
  2. HIDE. `.claude/settings.json` `skillOverrides` is GENERATED by this tool and holds only true duplicates:
     station.json `skill_hide` {name: {"state": off|user-invocable-only|name-only, "why": mirror|variant|fixture|harness,
     "of": "<canonical>"}} plus any duplicate row (variant/fixture/mirror/symlink) whose path sits directly under the
     root `.claude/skills/` (natively discovered). A hide whose why is not a duplicate kind is a violation.
     station.json `skillListingBudgetFraction`-style knob: station.json `skill_listing_budget_fraction` (number) is
     carried into settings.json `skillListingBudgetFraction`; absent = the key is absent (Claude Code default 1%).
     These two keys are the ONLY per-station content of the commons settings.json: commons_drift hashes the file
     with them removed (tools/gov/_gov.py GENERATED_SETTINGS_KEYS), and this tool's --check proves them current.
  3. REPORT. The listing budget is a REPORT against Claude Code's real budget, never a cap: every listed skill's
     name + description (capped at 1,536 chars per skill, the harness cap) against fraction x context_window_tokens
     (commons/defaults.json, 200,000) x 4 chars/token. Over budget -> one worklist row naming the fraction that
     would list every description in full. Nothing is ever hidden to fit.
Main has no station.json: nothing is surfaced and skillOverrides stays {}.

CLI: skill_surface.py [--write | --check | --report | --plan] [--root <dir>] [--selftest]
  --write   create/refresh the symlinks, remove stale lane symlinks (never a real directory), write the two keys.
  --check   (default) exit 1 when a planned symlink is missing, wrong or dangling, a stale lane symlink remains, the
            settings keys differ from the plan, or a skill_hide row hides a non-duplicate.
  --report  the listing-budget report (exit 0 always; worklist 1 when over budget).
  --plan    print the plan as JSON.
Exit: 0 clean · 1 violation · 2 unreadable input.
"""
import argparse
import json
import os
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import _uplib as U  # noqa: E402

LANE_PREFIXES = tuple(l + "/" for l in U.LANES)
SURFACE_KINDS = ("canonical",)
DUP_KINDS = ("variant", "fixture", "mirror", "symlink", "symlink_text")
HIDE_WHY = ("mirror", "variant", "fixture", "harness")
OVERRIDE_STATES = ("on", "name-only", "user-invocable-only", "off")
HIDDEN_STATES = ("user-invocable-only", "off")
GENERATED_KEYS = ("skillOverrides", "skillListingBudgetFraction")
DESC_CAP = 1536          # harness cap per skill (description + when_to_use), code.claude.com/docs/en/skills.md
CHARS_PER_TOKEN = 4
NAME_MAX = 64


def slug(s):
    s = re.sub(r"[^a-z0-9-]+", "-", str(s or "").lower())
    return re.sub(r"-{2,}", "-", s).strip("-")[:NAME_MAX].strip("-")


def _repo_slug(path):
    parts = Path(path).parts
    tree = parts[1] if len(parts) > 1 else ""
    return slug(tree.split("~", 1)[-1]) or "upstream"


def defaults(root):
    return U.load_json(Path(root) / "commons" / "defaults.json", {}) or {}


def settings_path(root):
    return Path(root) / ".claude" / "settings.json"


def load_rows(root):
    p = Path(root) / "router" / "skills.json"
    return (U.load_json(p, {}) or {}).get("skills", []) if p.exists() else []


def plan(root):
    """{'surface': [{name, target, id, kind}], 'overrides': {...}, 'fraction': float|None, 'violations': [...]}."""
    root = Path(root)
    st = U.station_json(root)
    out = {"surface": [], "overrides": {}, "fraction": None, "violations": [], "station": (st or {}).get("name")}
    if not st:
        return out
    skills_dir = root / ".claude" / "skills"
    taken = {p.name for p in skills_dir.iterdir() if p.is_dir() and not p.is_symlink()} if skills_dir.is_dir() else set()
    rows = load_rows(root)
    surf = []
    for r in sorted(rows, key=lambda r: (str(r.get("id") or ""), str(r.get("path") or ""))):
        path = (r.get("path") or "").replace("\\", "/")
        if r.get("kind") not in SURFACE_KINDS or r.get("route_to") or not path.endswith("/SKILL.md"):
            continue
        if not path.startswith(LANE_PREFIXES):
            continue  # already native (.claude/skills/...) or outside the lanes: nothing to surface
        base = slug(r.get("name")) or slug(Path(path).parent.name) or "skill"
        name = base
        if name in taken:
            name = (base[:NAME_MAX - 2 - len(_repo_slug(path)[:20])] + "--" + _repo_slug(path)[:20]).strip("-")
        i = 2
        while name in taken:
            name = "%s-%d" % (base[:NAME_MAX - 4], i)
            i += 1
        taken.add(name)
        surf.append({"name": name, "target": str(Path(path).parent.as_posix()), "id": r.get("id"),
                     "kind": "copy" if r.get("copy_of") else "canonical"})
    out["surface"] = surf
    ov = {}
    for name, spec in sorted((st.get("skill_hide") or {}).items()):
        spec = spec if isinstance(spec, dict) else {"state": spec}
        state, why = spec.get("state", "off"), spec.get("why")
        if state not in OVERRIDE_STATES:
            out["violations"].append("station.json skill_hide %s: state %r not one of %s" % (name, state, "|".join(OVERRIDE_STATES)))
            continue
        if why not in HIDE_WHY:
            out["violations"].append("station.json skill_hide %s: why %r is not a duplicate kind (%s); the listing cap is "
                                     "retired (DEC-core-0010), a real skill stays visible" % (name, why, "|".join(HIDE_WHY)))
            continue
        ov[name] = state
    for r in rows:
        path = (r.get("path") or "").replace("\\", "/")
        m = re.match(r"^\.claude/skills/([^/]+)/SKILL\.md$", path)
        if m and r.get("kind") in DUP_KINDS:
            ov.setdefault(m.group(1), "off")
    out["overrides"] = dict(sorted(ov.items()))
    frac = st.get("skill_listing_budget_fraction")
    if frac is not None:
        if not isinstance(frac, (int, float)) or not 0 < frac <= 1:
            out["violations"].append("station.json skill_listing_budget_fraction %r: want a number in (0, 1]" % (frac,))
        else:
            out["fraction"] = frac
    return out


def _link_target(root, target):
    return os.path.relpath(str(Path(root) / target), str(Path(root) / ".claude" / "skills"))


def _lane_symlinks(root):
    d = Path(root) / ".claude" / "skills"
    out = {}
    if not d.is_dir():
        return out
    for p in d.iterdir():
        if p.is_symlink():
            raw = os.readlink(str(p))
            rel = os.path.normpath(os.path.join(".claude/skills", raw)).replace("\\", "/")
            out[p.name] = (raw, rel)
    return out


def settings_with(root, pl):
    s = U.load_json(settings_path(root), {}) or {}
    s = dict(s)
    s["skillOverrides"] = pl["overrides"]
    if pl["fraction"] is None:
        s.pop("skillListingBudgetFraction", None)
    else:
        s["skillListingBudgetFraction"] = pl["fraction"]
    return s


def _dump_settings(obj):
    return json.dumps(obj, indent=1, ensure_ascii=False) + "\n"


def check(root, quiet=False):
    root = Path(root)
    pl = plan(root)
    viol = list(pl["violations"])
    work = []
    links = _lane_symlinks(root)
    planned = {s["name"]: s for s in pl["surface"]}
    for name, s in planned.items():
        p = root / ".claude" / "skills" / name
        want = _link_target(root, s["target"])
        if name not in links:
            viol.append(".claude/skills/%s: missing (-> %s); run python3 tools/upstream/skill_surface.py --write" % (name, s["target"]))
        elif links[name][0] != want:
            viol.append(".claude/skills/%s: points at %s, want %s" % (name, links[name][0], want))
        elif not (p / "SKILL.md").is_file():
            viol.append(".claude/skills/%s: dangling (no SKILL.md at %s)" % (name, s["target"]))
    for name, (raw, rel) in sorted(links.items()):
        if name not in planned and rel.startswith(LANE_PREFIXES):
            viol.append(".claude/skills/%s: stale lane symlink (-> %s) not in the plan" % (name, rel))
    sp = settings_path(root)
    cur = U.load_json(sp, {}) or {}
    want = settings_with(root, pl)
    for k in GENERATED_KEYS:
        if cur.get(k) != want.get(k):
            viol.append(".claude/settings.json %s: %s on disk, plan says %s" % (k, json.dumps(cur.get(k)), json.dumps(want.get(k))))
    st = U.station_json(root) or {}
    for k, v in sorted((st.get("skill_overrides") or {}).items()):
        work.append("station.json skill_overrides %s=%s: retired (DEC-core-0010; Claude Code never read it) - delete it, "
                    "or move a true duplicate to skill_hide" % (k, v))
    denom = len(planned) + len(pl["overrides"])
    if quiet:
        return (1 if viol else 0), viol, work
    return U.finish("skill_surface", viol, work, denom)


def write(root):
    root = Path(root)
    pl = plan(root)
    d = root / ".claude" / "skills"
    d.mkdir(parents=True, exist_ok=True)
    planned = {s["name"]: s for s in pl["surface"]}
    made = removed = 0
    for name, (raw, rel) in _lane_symlinks(root).items():
        want = _link_target(root, planned[name]["target"]) if name in planned else None
        if (name not in planned and rel.startswith(LANE_PREFIXES)) or (want and raw != want):
            (d / name).unlink()
            removed += 1
    for name, s in planned.items():
        p = d / name
        if p.is_symlink():
            continue
        if p.exists():
            print("skill_surface: .claude/skills/%s exists as a real directory; not replaced" % name)
            continue
        os.symlink(_link_target(root, s["target"]), str(p), target_is_directory=True)
        made += 1
    sp = settings_path(root)
    want = _dump_settings(settings_with(root, pl))
    cur = sp.read_text(encoding="utf-8") if sp.exists() else ""
    if cur != want:
        sp.parent.mkdir(parents=True, exist_ok=True)
        sp.write_text(want, encoding="utf-8")
    print("skill_surface: %d surfaced (%d new, %d replaced or removed) · %d hidden duplicate(s) · settings.json %s"
          % (len(planned), made, removed, len(pl["overrides"]), "written" if cur != want else "unchanged"))
    for v in pl["violations"]:
        print("  violation " + v)
    return 1 if pl["violations"] else 0


def listing(root):
    """[(name, listed_chars, state)] for every skill Claude Code would list from this root, as it reads it."""
    root = Path(root)
    d = root / ".claude" / "skills"
    ov = (U.load_json(settings_path(root), {}) or {}).get("skillOverrides") or {}
    out = []
    if not d.is_dir():
        return out
    for p in sorted(d.iterdir()):
        f = p / "SKILL.md"
        if not p.is_dir() or not f.is_file():
            continue
        try:
            fm = U.frontmatter(f.read_text(encoding="utf-8", errors="replace")) or {}
        except Exception:
            fm = {}
        state = ov.get(p.name, "on")
        if str(fm.get("disable-model-invocation", "")).lower() == "true":
            state = "user-invocable-only"
        desc = str(fm.get("description") or "") + str(fm.get("when_to_use") or "")
        if state in HIDDEN_STATES:
            n = 0
        elif state == "name-only":
            n = len(p.name)
        else:
            n = len(p.name) + min(len(desc), DESC_CAP)
        out.append((p.name, n, state))
    return out


def budget(root):
    """(fraction, context tokens, budget chars)."""
    dfl = defaults(root)
    frac = (U.load_json(settings_path(root), {}) or {}).get("skillListingBudgetFraction") or dfl.get("skill_listing_budget_fraction", 0.01)
    ctx = int(dfl.get("context_window_tokens", 200000))
    return frac, ctx, int(frac * ctx * CHARS_PER_TOKEN)


def report(root, quiet=False):
    rows = listing(root)
    listed = [r for r in rows if r[2] not in HIDDEN_STATES]
    used = sum(r[1] for r in listed)
    frac, ctx, cap = budget(root)
    work = []
    need = used / float(ctx * CHARS_PER_TOKEN) if ctx else 0
    if used > cap:
        work.append("listing %d chars > budget %d chars (%.3g of %d tokens x %d chars): Claude Code drops the least-invoked "
                    "descriptions (every name stays listed); to list all in full set station.json "
                    "skill_listing_budget_fraction >= %.3f and run skill_surface.py --write" % (used, cap, frac, ctx, CHARS_PER_TOKEN, need))
    line = ("  listing: %d skill(s) listed, %d hidden · %d chars of a %d-char budget (%.3g x %d tokens x %d) · %s"
            % (len(listed), len(rows) - len(listed), used, cap, frac, ctx, CHARS_PER_TOKEN,
               "fits" if used <= cap else "OVER: descriptions get truncated, names stay"))
    if quiet:
        return work, line, used, cap
    rc = U.finish("listing_report", [], work, len(rows))
    print(line)
    return rc


# ---------------------------------------------------------------- selftest
def _mk(root, rel, text):
    p = Path(root) / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")


def selftest():
    import tempfile
    fails, n = [], 0

    def ok(c, m):
        nonlocal n
        n += 1
        if not c:
            fails.append(m)

    with tempfile.TemporaryDirectory() as t:
        r = Path(t)
        _mk(r, "commons/defaults.json", json.dumps({"context_window_tokens": 1000}))
        _mk(r, ".claude/settings.json", _dump_settings({"claudeMdExcludes": ["**/upstream/**"], "skillOverrides": {}}))
        _mk(r, ".claude/skills/closeout/SKILL.md", "---\nname: closeout\ndescription: close a pass\n---\n")
        # main: no station.json -> nothing surfaced, {} stays
        ok(plan(r)["surface"] == [] and check(r, quiet=True)[0] == 0, "main: empty plan, clean")
        _mk(r, "station.json", json.dumps({"name": "x", "skill_overrides": {"checkpoint": "user-invocable-only"}}))
        for rel, desc in (("repertoire/o~alpha/skills/foo/SKILL.md", "foo skill " + "a" * 200),
                          ("repertoire/o~beta/skills/foo/SKILL.md", "another foo"),
                          ("upstream/o~gamma/_upstream_claude/skills/closeout/SKILL.md", "upstream closeout"),
                          ("repertoire/o~alpha/.cursor/skills/foo/SKILL.md", "mirror"),
                          ("repertoire/o~alpha/plugin/skills/foo/SKILL.md", "variant")):
            _mk(r, rel, "---\nname: %s\ndescription: %s\n---\nbody\n" % (Path(rel).parent.name, desc))
        rows = [{"id": "1:a", "name": "foo", "kind": "canonical", "path": "repertoire/o~alpha/skills/foo/SKILL.md", "route_to": None},
                {"id": "2:b", "name": "foo", "kind": "canonical", "path": "repertoire/o~beta/skills/foo/SKILL.md", "route_to": None, "copy_of": "y"},
                {"id": "3:c", "name": "closeout", "kind": "canonical", "path": "upstream/o~gamma/_upstream_claude/skills/closeout/SKILL.md", "route_to": None},
                {"id": "4:d", "name": "foo", "kind": "mirror", "path": None, "route_to": "1:a"},
                {"id": "5:e", "name": "foo", "kind": "variant", "path": "repertoire/o~alpha/plugin/skills/foo/SKILL.md", "route_to": None},
                {"id": "6:f", "name": "bar", "kind": "canonical", "path": ".claude/skills/closeout/SKILL.md", "route_to": None}]
        _mk(r, "router/skills.json", json.dumps({"skills": rows}))
        pl = plan(r)
        names = [s["name"] for s in pl["surface"]]
        ok(names == ["foo", "foo--beta", "closeout--gamma"], "surface names + collisions (kit skill, earlier row): %r" % names)
        ok(all(s["kind"] in ("canonical", "copy") for s in pl["surface"]) and pl["surface"][1]["kind"] == "copy", "a held copy is surfaced")
        rc, v, w = check(r, quiet=True)
        ok(rc == 1 and any("missing" in x for x in v), "check: missing symlinks are violations: %r" % v)
        ok(any("retired" in x for x in w), "station.json skill_overrides is reported retired: %r" % w)
        ok(write(r) == 0 and check(r, quiet=True)[0] == 0, "write then check clean: %r" % (check(r, quiet=True)[1],))
        ok((r / ".claude/skills/foo/SKILL.md").read_text().startswith("---\nname: foo"), "symlink resolves to the lane SKILL.md")
        ok(os.readlink(str(r / ".claude/skills/foo")) == "../../repertoire/o~alpha/skills/foo", "relative link target")
        ok((r / ".claude/skills/foo--beta").is_symlink() and not (r / ".claude/skills/foo--beta").resolve().is_symlink(), "a symlink, lane bytes not copied")
        # stale + wrong links
        os.symlink("../../repertoire/o~alpha/plugin/skills/foo", str(r / ".claude/skills/old"))
        ok(any("stale" in x for x in check(r, quiet=True)[1]), "a stale lane symlink is a violation")
        write(r)
        ok(not (r / ".claude/skills/old").exists() and check(r, quiet=True)[0] == 0, "write removes the stale link")
        # hides: duplicate kinds only
        _mk(r, "station.json", json.dumps({"name": "x", "skill_hide": {"foo--beta": {"state": "off", "why": "variant", "of": "foo"},
                                                                         "closeout--gamma": {"state": "off", "why": "too many skills"}}}))
        pl = plan(r)
        ok(pl["overrides"] == {"foo--beta": "off"} and any("not a duplicate kind" in x for x in pl["violations"]),
           "skill_hide keeps duplicates, rejects a cap-style hide: %r %r" % (pl["overrides"], pl["violations"]))
        ok(check(r, quiet=True)[0] == 1, "settings drift from the plan is a violation")
        write(r)
        s = json.loads((r / ".claude/settings.json").read_text())
        ok(s["skillOverrides"] == {"foo--beta": "off"} and s["claudeMdExcludes"] == ["**/upstream/**"], "write keeps other settings keys")
        # natively discovered duplicate row under the root .claude/skills -> off
        rows.append({"id": "7:g", "name": "closeout", "kind": "variant", "path": ".claude/skills/closeout/SKILL.md", "route_to": None})
        _mk(r, "router/skills.json", json.dumps({"skills": rows}))
        ok(plan(r)["overrides"].get("closeout") == "off", "a native duplicate row is hidden")
        # listing report: real budget, never a cap
        _mk(r, "station.json", json.dumps({"name": "x"}))
        _mk(r, "router/skills.json", json.dumps({"skills": rows[:6]}))
        write(r)
        work, line, used, cap = report(r, quiet=True)
        ok(cap == 40 and used > cap and work and "skill_listing_budget_fraction >=" in work[0], "over budget -> worklist naming the fraction: %r" % work)
        ok(len([x for x in listing(r) if x[2] == "on"]) == 4, "nothing is hidden to fit: %r" % listing(r))
        _mk(r, "station.json", json.dumps({"name": "x", "skill_listing_budget_fraction": 1}))
        write(r)
        ok(json.loads((r / ".claude/settings.json").read_text()).get("skillListingBudgetFraction") == 1, "fraction carried into settings.json")
        work, line, used, cap = report(r, quiet=True)
        ok(cap == 4000 and not work and "fits" in line, "raised fraction fits: %s" % line)
        ok(slug("Résumé Tailor (v2)") == "r-sum-tailor-v2" and len(slug("x" * 99)) == 64, "slug")
    if fails:
        print("skill_surface selftest FAILED (%d of %d)" % (len(fails), n))
        for f in fails:
            print(" - " + f)
        return 1
    print("skill_surface selftest OK (%d cases)" % n)
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    g.add_argument("--report", action="store_true")
    g.add_argument("--plan", action="store_true")
    g.add_argument("--selftest", action="store_true")
    ap.add_argument("--root", default=None)
    a = ap.parse_args(argv)
    if a.selftest:
        return selftest()
    root = U.find_root(a.root)
    try:
        if a.write:
            return write(root)
        if a.report:
            return report(root)
        if a.plan:
            print(json.dumps(plan(root), indent=1))
            return 0
        return check(root)
    except (OSError, ValueError) as e:
        print("skill_surface: unreadable input (%s)" % e)
        return 2


if __name__ == "__main__":
    sys.exit(main())
