#!/usr/bin/env python3
"""gen_station_map.py — map/STATIONS.md: one row per `station/*` branch, rendered against main (kit main only).

Earned by: lettuce docs/plan/BRANCH_MAP.md + tools/gen_branch_map.py (every branch rendered against main so a branch
that fell behind or forked off an old base is SEEN, not remembered); only the "render branches against main" shape is
ported — its fixed classification lists (READY, CHAIN-6C, ...) stay home. Retires: nothing in the kit.
Row: branch · purpose (`git show <ref>:station.json`, else `<ref>:map/station_dirs.json` meta.purpose) · commits behind
main · merge-base == the newest `commons-v*` tag · upstream/LOCK.json row count · last commit subject.
A WORKLIST, never a gate: it depends on refs that move outside the repo's own text. `--check` exits 1 on drift.
On a station branch (station.json present) every mode prints `station_map: skipped (not main)` and exits 0.
Knob: map L. CLI: --write | --check | --list-outputs | --selftest  [--root DIR]. Exit 0/1/2.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _common as C  # noqa: E402

TOOL = "tools/map/gen_station_map.py"
OUT = "map/STATIONS.md"


def show_json(root, ref, path):
    r = C.git(root, "show", "%s:%s" % (ref, path))
    if r.returncode != 0:
        return None
    try:
        return json.loads(r.stdout)
    except ValueError:
        return {"_unreadable": True}


def main_name(root):
    """The kit's main ref (tools/kit/_kit.main_ref: local main, local claude/stable-kit-main, then remote forms -
    REPRODUCE F2); plain `main` when the kit tools are absent. reconcile-01: a hosted checkout with local station/*
    branches and no local `main` made this check UNREADABLE."""
    kit = Path(root) / "tools" / "kit"
    if (kit / "_kit.py").is_file():
        sys.path.insert(0, str(kit))
        try:
            import _kit
            return _kit.main_ref(str(root)) or "main"
        except Exception:  # noqa: BLE001 - fall back to the literal name
            return "main"
    return "main"


def rows(root):
    main = main_name(root)
    refs = C.git(root, "for-each-ref", "--format=%(refname:short)", "refs/heads/station/", check=True).stdout.split()
    tags = C.git(root, "tag", "--list", "commons-v*", "--sort=-v:refname").stdout.split()
    tag_sha = C.git(root, "rev-list", "-n1", tags[0]).stdout.strip() if tags else None
    out = []
    for ref in sorted(refs):
        sj = show_json(root, ref, "station.json") or {}
        sd = show_json(root, ref, "map/station_dirs.json") or {}
        purpose = sj.get("purpose") or (sd.get("meta") or {}).get("purpose") or ("UNREADABLE station.json" if sj.get("_unreadable") else "-")
        behind = C.git(root, "rev-list", "--count", "%s..%s" % (ref, main), check=True).stdout.strip()
        mb = C.git(root, "merge-base", main, ref).stdout.strip()
        lock = show_json(root, ref, "upstream/LOCK.json") or {}
        nlock = len(lock.get("rows", [])) if isinstance(lock, dict) else 0
        subj = C.git(root, "log", "-1", "--format=%s", ref).stdout.strip()
        out.append({"branch": ref, "purpose": purpose, "behind": int(behind or 0),
                    "base": ("yes (%s)" % tags[0]) if tag_sha and mb == tag_sha else ("no" if tags else "no commons tag"),
                    "lock": nlock, "subject": subj})
    return out


def render(rs):
    esc = lambda s: str(s).replace("|", "\\|")
    L = ["<!-- GENERATED by %s from the station/* branches — run python3 %s --write -->" % (TOOL, TOOL),
         "owner: tools/map/gen_station_map.py · status: GENERATED · date: see git log · supersedes: none · audit: python3 %s --check" % TOOL,
         "", "# Stations", "", "%d station branch(es) rendered against `main`. Open one: `git worktree add ~/stations/<x> station/<x>`." % len(rs), "",
         "| branch | purpose | behind main | merge-base == commons tag | LOCK rows | last commit |", "|---|---|---|---|---|---|"]
    L += ["| `%s` | %s | %d | %s | %d | %s |" % (r["branch"], esc(r["purpose"]), r["behind"], r["base"], r["lock"], esc(r["subject"])) for r in rs]
    return "\n".join(L) + "\n"


def selftest():
    import tempfile
    ok = True
    with tempfile.TemporaryDirectory() as t:
        C.git_init_fixture(t)
        Path(t, "README.md").write_text("kit\n")
        C.commit_fixture(t, "main: base")
        C.git(t, "tag", "commons-v1")
        for name, purpose in (("a", "alpha work"), ("b", "beta work")):
            C.git(t, "switch", "-q", "-c", "station/" + name, "main")
            Path(t, "station.json").write_text(json.dumps({"name": name, "purpose": purpose}))
            Path(t, "upstream").mkdir(exist_ok=True)
            Path(t, "upstream", "LOCK.json").write_text(json.dumps({"rows": [{"repo": "o/r"}] * (1 if name == "a" else 2)}))
            C.commit_fixture(t, "station/%s: overlay" % name)
            C.git(t, "switch", "-q", "main")
        Path(t, "README.md").write_text("kit v2\n")
        C.commit_fixture(t, "main: commons change")
        C.git(t, "switch", "-q", "station/b")
        C.git(t, "-c", "user.name=kit", "-c", "user.email=kit@localhost", "merge", "-q", "--no-edit", "main")
        C.git(t, "switch", "-q", "main")
        rs = {r["branch"]: r for r in rows(t)}
        good = (set(rs) == {"station/a", "station/b"} and rs["station/a"]["behind"] == 1 and rs["station/b"]["behind"] == 0
                and rs["station/a"]["purpose"] == "alpha work" and rs["station/b"]["lock"] == 2 and rs["station/a"]["base"].startswith("yes"))
        if not good:
            ok = False
            print("FAIL rows", rs)
        Path(t, "map").mkdir()
        Path(t, OUT).write_text(render(rows(t)))
        if main(["--root", t, "--check"]) != 0:
            ok = False
            print("FAIL clean check")
        Path(t, OUT).write_text(render(rows(t)) + "x")
        if main(["--root", t, "--check"]) != 1:
            ok = False
            print("FAIL drift must exit 1")
        Path(t, "station.json").write_text("{}")
        if main(["--root", t, "--check"]) != 0:
            ok = False
            print("FAIL station branch skips")
    print("selftest OK" if ok else "selftest FAILED")
    return 0 if ok else 1


def main(argv):
    root, argv = C.root_arg(argv)
    if "--selftest" in argv:
        return selftest()
    if (Path(root) / "station.json").exists():
        if "--list-outputs" not in argv:
            print(C.skipped("station_map", "not main"))
        return 0
    if "--list-outputs" in argv:
        print(OUT)
        return 0
    if not C.map_at_least(root, "L"):
        print(C.skipped("station_map", "knob map=%s" % C.knob(root, "map")))
        return 0
    try:
        if not C.is_git(root):
            raise C.Unreadable("not a git repo")
        rs = rows(root)
    except C.Unreadable as e:
        print("station_map: UNREADABLE %s" % e)
        return 2
    want = render(rs)
    if "--write" in argv:
        C.write_if_changed(Path(root) / OUT, want)
        print("station_map: wrote %s (%d station(s))" % (OUT, len(rs)))
        return 0
    drift = C.read_text(root, OUT) != want
    print(C.headline("station_map", 0, int(drift) + sum(1 for r in rs if r["behind"]), len(rs)))
    if drift:
        print("DRIFT %s differs from its render (python3 %s --write)" % (OUT, TOOL))
    for r in rs:
        if r["behind"]:
            print("BEHIND %s is %d commit(s) behind main (python3 tools/kit/sync.py on that branch)" % (r["branch"], r["behind"]))
    return 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
