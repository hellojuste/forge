#!/usr/bin/env python3
"""gen_solutions.py — the solutions-before-building catalog (map/catalog.json + map/tags.json) -> map/SOLUTIONS.md.

Earned by: lettuce `docs/catalog/LIB_OVERLAP.md` (2026-07-31: a parallel type was built beside an existing one
because the "does it exist?" check was skipped) and `tools/audit_catalog.py` (the "0 uncatalogued" tripwire did not
fire for ELEVEN days: its glob was one level deep and an upload landed one directory deeper — "a tripwire is a claim
about where the wire is"). Hence `**` scope globs on the full path, and every exclusion prints prefix · reason · count.
Retires: lettuce's 832 Markdown dossiers + build_index.py (corpus-scale; a station has tens of things).
Tags are a CLOSED vocabulary (map/tags.json): add the tag first, never freelance one in an entry.
Gates (exit 1): INDEX-DRIFT · UNCATALOGUED · DEAD-ENTRY · TAG. Knob: map S+ (XS prints a named skip).
CLI: --write | --check | --list-outputs | --selftest  [--root DIR]. Exit 0/1/2.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _common as C  # noqa: E402

TOOL = "tools/map/gen_solutions.py"
OUT = "map/SOLUTIONS.md"
ORDER = {"working": 0, "parked": 1}


def render(root):
    cat = C.load_map(root, "catalog")
    tags = C.load_map(root, "tags")
    ups = C.load_map(root, "upstream", required=False).get("upstreams") or {}
    entries = cat.get("entries") or {}
    L = ["<!-- GENERATED by %s from map/catalog.json + map/upstream.json + map/tags.json — edit those, then run python3 %s --write -->" % (TOOL, TOOL),
         "owner: map/catalog.json · status: GENERATED · date: see git log · supersedes: none · audit: python3 %s --check" % TOOL, "",
         "# Solutions — read before building", "",
         "%d catalogued thing(s) · %d upstream(s) · %d problem tag(s). Search: `python3 tools/map/find.py <words>`." % (len(entries), len(ups), len(tags.get("problems") or {})), ""]
    for tag, desc in sorted((tags.get("problems") or {}).items()):
        mine = sorted(((k, e) for k, e in entries.items() if tag in (e.get("solves") or [])),
                      key=lambda x: (ORDER.get(x[1].get("status"), 2), x[0]))
        theirs = sorted((k, e) for k, e in ups.items() if tag in (e.get("solves") or []))
        if not mine and not theirs:
            continue
        L += ["## %s" % tag, "", "_%s_" % desc, ""]
        L += ["- `%s` — %s (%s): %s%s" % (k, e.get("title", ""), e.get("status", "?"), e.get("purpose", ""),
                                         (" · see also " + ", ".join(e["see_also"])) if e.get("see_also") else "") for k, e in mine]
        L += ["- upstream:%s — when %s · entry `%s`%s" % (k, e.get("when", "-"), e.get("entry") or e.get("url") or "-",
                                                       (" · instructions: " + ", ".join(e["instructions"])) if e.get("instructions") else "")
              for k, e in theirs]
        L.append("")
    return "\n".join(L)


def check(root):
    cat = C.load_map(root, "catalog")
    tags = set((C.load_map(root, "tags").get("problems") or {}).keys())
    entries = cat.get("entries") or {}
    V, W = [], []
    if C.read_text(root, OUT) != render(root):
        V.append("INDEX-DRIFT %s differs from its render (python3 %s --write)" % (OUT, TOOL))
    domain, _, _ = C.domain_files(root)
    excl = cat.get("exclusions") or []
    counts = {x["prefix"]: 0 for x in excl}
    in_scope = [f for f in domain if C.any_glob(f, cat.get("scope") or [])]
    for f in in_scope:
        ex = next((x["prefix"] for x in excl if f.startswith(x["prefix"])), None)
        if ex:
            counts[ex] += 1
        elif f not in entries:
            V.append("UNCATALOGUED %s: matched by scope, no map/catalog.json entry" % f)
    for k, e in sorted(entries.items()):
        if not (Path(root) / k).exists():
            V.append("DEAD-ENTRY %s: catalog key does not resolve" % k)
        for t in e.get("solves") or []:
            if t not in tags:
                V.append("TAG %s: %r is not in map/tags.json" % (k, t))
    W += ["EXCLUDED %s · %s · %d file(s)" % (x["prefix"], x.get("reason", "?"), counts[x["prefix"]]) for x in excl]
    return V, W, len(in_scope)


def selftest():
    import json
    import tempfile
    ok = True

    def mk(t, entries, files, tags=("prior-art",)):
        Path(t, "map").mkdir(parents=True, exist_ok=True)
        Path(t, "map", "catalog.json").write_text(json.dumps({"scope": ["tools/**/*.py"], "exclusions": [{"prefix": "tools/vendor/", "reason": "r"}],
                                                              "entries": entries}))
        Path(t, "map", "tags.json").write_text(json.dumps({"problems": {x: "d" for x in tags}}))
        for f in files:
            Path(t, f).parent.mkdir(parents=True, exist_ok=True)
            Path(t, f).write_text("x")
    good = {"tools/find.py": {"title": "t", "purpose": "p", "solves": ["prior-art"], "status": "working"}}
    cases = [("clean", good, ["tools/find.py", "tools/vendor/v.py"], 0),
             ("two dirs deep under **", good, ["tools/find.py", "tools/a/b/deep.py"], 1),
             ("undeclared tag", {"tools/find.py": dict(good["tools/find.py"], solves=["nope"])}, ["tools/find.py"], 1),
             ("dead entry", dict(good, **{"tools/gone.py": {"solves": []}}), ["tools/find.py"], 1), ("drift", good, ["tools/find.py"], 1)]
    for name, entries, files, want in cases:
        with tempfile.TemporaryDirectory() as t:
            mk(t, entries, files)
            Path(t, OUT).write_text(render(t) + ("x" if name == "drift" else ""))
            V, W, _ = check(t)
            if (1 if V else 0) != want or (name == "clean" and "EXCLUDED tools/vendor/ · r · 1 file(s)" not in W):
                ok = False
                print("FAIL", name, V, W)
    print("selftest OK" if ok else "selftest FAILED")
    return 0 if ok else 1


def main(argv):
    root, argv = C.root_arg(argv)
    if "--selftest" in argv:
        return selftest()
    if not C.map_at_least(root, "S") and "--list-outputs" not in argv:
        print(C.skipped("catalog", "knob map=%s" % C.knob(root, "map")))
        return 0
    try:
        if "--list-outputs" in argv:
            print(OUT if C.map_at_least(root, "S") else "")
            return 0
        if "--write" in argv:
            print("catalog: %s" % ("wrote " + OUT if C.write_if_changed(Path(root) / OUT, render(root)) else "unchanged"))
            return 0
        V, W, d = check(root)
    except C.Unreadable as e:
        print("catalog: UNREADABLE %s" % e)
        return 2
    print(C.headline("catalog", len(V), len(W), d))
    for x in V + W:
        print(x)
    return 1 if V else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
