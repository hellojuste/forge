#!/usr/bin/env python3
"""map_check.py — THE one driver of the mapping programme: write, check, quick, list, coverage, selftest.

Earned by: lettuce `tools/regen_all.py` ("two drivers regenerated the same files from two typed lists that disagreed
... each driver left a different file stale") — so GENERATORS is typed ONCE, here, and coverage is DERIVED from the
tree's own declarations, never typed: a tracked file that declares itself GENERATED must be an output of a generator
listed here (map family) or name an existing generator outside tools/map/ (other programmes' generators, e.g.
tools/brain.py, tools/gov/gen_ownership.py). Retires: regen_all --push race batching (a station has one writer).
Merge rule: a generated conflict is never hand-merged — take either side, then run `--write` (tools/kit/sync.py does).
Modes: --write (generators in dependency order, atlas last) · --check (every generator + check; one headline each with
its class; gates fail, worklists never do) · --quick (generators' --check only; for SessionStart) · --list ·
--coverage (UNCOVERED generated files exit 1) · --selftest (every map script's selftest + the coverage mutant).
Exit 0/1/2. [--root DIR]
"""
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _common as C  # noqa: E402

HERE = Path(__file__).resolve().parent
GENERATORS = [
    ("tools/map/gen_dir_readmes.py", ["<dir>/README.md for readme: generated"]),
    ("tools/map/gen_solutions.py", ["map/SOLUTIONS.md"]),
    ("tools/map/usage_map.py", ["map/usage.json"]),
    ("tools/map/gen_atlas.py", ["map/atlas.json", "map/ATLAS.md"]),
]
CHECKS = [  # (script, args, class)
    ("tools/map/upstream_check.py", ["--check"], "GATE"), ("tools/map/check_paths.py", ["--check"], "GATE"),
    ("tools/map/gen_dir_readmes.py", ["--check"], "GATE"), ("tools/map/gen_solutions.py", ["--check"], "GATE"),
    ("tools/map/usage_map.py", ["--check"], "GATE"), ("tools/map/gen_atlas.py", ["--check"], "GATE"),
    ("tools/map/gen_dir_readmes.py", ["--placement"], "WORKLIST"), ("tools/map/usage_map.py", ["--cold"], "WORKLIST"),
    ("tools/map/gen_atlas.py", ["--orphans"], "WORKLIST"), ("tools/map/gen_station_map.py", ["--check"], "WORKLIST"),
]
SELFTESTS = ["_common.py", "gen_dir_readmes.py", "upstream_check.py", "gen_solutions.py", "find.py", "usage_map.py",
             "gen_atlas.py", "check_paths.py", "gen_station_map.py", "hooks/prior_art.py", "hooks/deny_generated_edit.py",
             "hooks/usage_log.py"]


def run(root, script, args, timeout=180):
    p = Path(root) / script
    if not p.exists():
        p = HERE.parents[1] / script
    try:
        r = subprocess.run([sys.executable, str(p)] + args + ["--root", str(root)], capture_output=True, text=True, timeout=timeout)
        return r.returncode, r.stdout
    except subprocess.TimeoutExpired:
        return None, "TIMEOUT %s" % script


def outputs(root, generators):
    outs = set()
    for script, _ in generators:
        rc, out = run(root, script, ["--list-outputs"])
        if rc != 0:
            raise C.Unreadable("%s --list-outputs failed" % script)
        outs |= {l.strip() for l in out.splitlines() if l.strip()}
    return outs


def coverage(root, generators=GENERATORS):
    outs = outputs(root, generators)
    domain, _, _ = C.domain_files(root)
    bad, gen = [], 0
    for f in domain:
        if not C.file_declares_generated(Path(root) / f):
            continue
        gen += 1
        if f in outs:
            continue
        head = "".join((C.read_text(root, f) or "").splitlines(True)[:3])
        m = re.search(r'GENERATED by (\S+?)(?:\s|$)|"_generated_by"\s*:\s*"([^"]+)"', head)
        named = (m.group(1) or m.group(2)) if m else None
        if named and not named.startswith("tools/map/") and (Path(root) / named.split()[0]).exists():
            continue
        bad.append("UNCOVERED %s (declares %s)" % (f, named or "no generator"))
    return bad, gen


def check(root, quick=False):
    rows = [(s, ["--check"], "GATE") for s, _ in GENERATORS] if quick else CHECKS
    red, wl, lines = 0, 0, []
    for script, args, cls in rows:
        rc, out = run(root, script, args)
        first = (out or "").splitlines()[0] if (out or "").strip() else "%s: no output" % script
        m = re.search(r"(\d+) violation\(s\) · (\d+) worklist", first)
        if cls == "GATE" and (rc not in (0,) or (m and int(m.group(1)))):
            red += 1
        if m:
            wl += int(m.group(2))
        lines.append("[%s] %s%s" % (cls, first, "" if rc in (0, 1) else " (rc=%s)" % rc))
    return red, wl, lines


def selftest():
    import tempfile
    ok = True
    for s in SELFTESTS:
        r = subprocess.run([sys.executable, str(HERE / s), "--selftest"], capture_output=True, text=True, timeout=300)
        good = r.returncode == 0 and "selftest OK" in r.stdout
        print("%s %s" % ("PASS" if good else "FAIL", s))
        ok &= good
    with tempfile.TemporaryDirectory() as t:
        for f, x in {"map/dirs.json": "{}", "map/catalog.json": '{"entries": {}}', "map/tags.json": '{"problems": {}}',
                     "map/atlas_schema.json": '{"node_classes": {}, "edge_kinds": {}}', "map/upstream.json": '{"upstreams": {}}',
                     "map/usage.json": '{\n "_generated_by": "tools/map/usage_map.py"\n}\n',
                     "governance/OWN.md": "<!-- GENERATED by tools/gov/gen_x.py -->\n", "tools/gov/gen_x.py": "x\n"}.items():
            Path(t, f).parent.mkdir(parents=True, exist_ok=True)
            Path(t, f).write_text(x)
        full, _ = coverage(t)
        mutant, _ = coverage(t, [g for g in GENERATORS if g[0] != "tools/map/usage_map.py"])
        good = not full and any("map/usage.json" in b for b in mutant)
        print("%s coverage mutant (drop usage_map.py -> UNCOVERED map/usage.json)" % ("PASS" if good else "FAIL"))
        ok &= good
    print("selftest OK" if ok else "selftest FAILED")
    return 0 if ok else 1


def main(argv):
    root, argv = C.root_arg(argv)
    if "--selftest" in argv:
        return selftest()
    try:
        if "--list" in argv:
            for s, outs in GENERATORS:
                print("GENERATOR %s -> %s" % (s, ", ".join(outs)))
            for s, a, cls in CHECKS:
                print("CHECK [%s] %s %s" % (cls, s, " ".join(a)))
            return 0
        if "--coverage" in argv:
            bad, n = coverage(root)
            print(C.headline("coverage", len(bad), 0, n))
            print("\n".join(bad))
            return 1 if bad else 0
        if "--write" in argv:
            rc = 0
            for s, _ in GENERATORS:
                r, out = run(root, s, ["--write"])
                print((out or "").strip() or "%s: no output" % s)
                rc = max(rc, 0 if r == 0 else 2)
            return rc
        red, wl, lines = check(root, quick="--quick" in argv)
    except C.Unreadable as e:
        print("map: UNREADABLE %s" % e)
        return 2
    print(C.headline("map", red, wl, len(lines)))
    print("\n".join(lines))
    print("map: %d gate(s) red · %d worklist count(s)" % (red, wl))
    return 1 if red else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
