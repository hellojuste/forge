#!/usr/bin/env python3
"""_common.py — the one shared core of the mapping programme (tools/map/*).

Earned by: lettuce `tools/regen_all.py` ("two drivers regenerated the same files from two typed lists that
disagreed"), `tools/hooks/deny_generated_edit.py` (matching the bare word GENERATED hit 489 files, so the
declaration SENTENCE is required) and L310 (a rule with no stated domain becomes an undrainable worklist).

Owner of (every other file imports or points here; `tools/gov/_gov.py` carries a byte-equal fallback):
  * GEN_DECL / declares_generated(text)   — the generated-file declaration, first three lines only;
  * tracked_files(root)                    — `git ls-files -co --exclude-standard`, else an os.walk;
  * classify(rel, cfg)                     — excluded | held | domain  (KIT contract commons-mapbrain 1.3);
  * load_map(root, name)                   — commons `map/<name>.json` + station overlay `map/station_<name>.json`;
  * knob(root, programme)                  — station.json knobs > commons/defaults.json knobs > main default;
  * headline(name, n, m, d)                — `<check>: <n> violation(s) · <m> worklist · denominator <d>`;
  * dump_json(obj)                         — byte-stable JSON (indent 1, sorted keys, utf-8, trailing newline).
Exit codes used by every map script: 0 clean · 1 violation/drift · 2 unreadable input, usage or git failure.
Not runnable on its own except `--selftest`.
"""
import fnmatch
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MAP_DIR_NAME = "map"
SEP = "·"
GEN_DECL = re.compile(r'GENERATED by \S+|GENERATED\W+(?:do not edit|never hand-edit|regenerat)|"_generated_by"\s*:', re.I)
EXCLUDE_DEFAULT = [".upstream/", ".git/", ".usage/", ".cache/"]
HELD_DEFAULT = ["repertoire/", "upstream/", "study/", "nc-lane/"]
WALK_SKIP = {".git", ".upstream", ".usage", ".cache", "__pycache__", ".station", "node_modules"}
MAP_LEVELS = ["XS", "S", "M", "L"]
BRAIN_LEVELS = ["tiny", "small", "medium", "large"]
MAIN_KNOBS = {"map": "L", "brain": "small", "gov": "standard"}


class Unreadable(Exception):
    """A configured input that failed to read: never an empty read (exit 2)."""


def declares_generated(text):
    return any(GEN_DECL.search(l) for l in (text or "").splitlines()[:3])


def file_declares_generated(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            head = "".join(fh.readline() for _ in range(3))
    except OSError:
        return False
    return declares_generated(head)


def dump_json(obj):
    return json.dumps(obj, indent=1, sort_keys=True, ensure_ascii=False) + "\n"


def load_json(path, default=None):
    p = Path(path)
    if not p.exists():
        if default is not None:
            return default
        raise Unreadable("%s: missing" % p)
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (ValueError, OSError) as e:
        raise Unreadable("%s: %s" % (p, e))


def headline(name, n, m, d):
    return "%s: %d violation(s) %s %d worklist %s denominator %d" % (name, n, SEP, m, SEP, d)


def skipped(name, why):
    return "%s: skipped (%s)" % (name, why)


def git(root, *args, check=False):
    r = subprocess.run(["git", "-C", str(root)] + list(args), capture_output=True, text=True,
                       encoding="utf-8", errors="replace")
    if check and r.returncode != 0:
        raise Unreadable("git %s: %s" % (" ".join(args), r.stderr.strip()[:200]))
    return r


def is_git(root):
    return (Path(root) / ".git").exists()


def tracked_files(root):
    """Tracked + untracked-not-ignored files, '/'-separated, sorted. A failed git read is Unreadable."""
    root = Path(root)
    if is_git(root):
        r = git(root, "ls-files", "-co", "--exclude-standard", "-z")
        if r.returncode != 0:
            raise Unreadable("git ls-files: %s" % r.stderr.strip()[:200])
        return sorted(p for p in set(r.stdout.split("\0")) if p and (root / p).is_file())
    out = []
    for dp, dns, fns in os.walk(root):
        dns[:] = sorted(d for d in dns if d not in WALK_SKIP)
        for fn in fns:
            out.append(os.path.relpath(os.path.join(dp, fn), root).replace(os.sep, "/"))
    return sorted(out)


def map_dir(root):
    return Path(root) / MAP_DIR_NAME


def _merge(a, b):
    if isinstance(a, dict) and isinstance(b, dict):
        out = dict(a)
        for k, v in b.items():
            out[k] = _merge(a[k], v) if k in a else v
        return out
    if isinstance(a, list) and isinstance(b, list):
        return a + [x for x in b if x not in a]
    return b


def load_map(root, name, required=True):
    """Commons registry + station overlay. A missing commons file is Unreadable when required."""
    base = map_dir(root) / ("%s.json" % name)
    if not base.exists() and not required:
        data = {}
    else:
        data = load_json(base)
    over = map_dir(root) / ("station_%s.json" % name)
    if over.exists():
        data = _merge(data, load_json(over))
    return data


def station_json(root):
    p = Path(root) / "station.json"
    if not p.exists():
        return None
    return load_json(p)


def station_name(root):
    try:
        sj = station_json(root)
    except Unreadable:
        return "core"
    return (sj or {}).get("name") or "core"


def knob(root, programme):
    """'map' -> XS|S|M|L ; 'brain' -> tiny|small|medium|large. Unreadable station.json -> main default."""
    for src in (Path(root) / "station.json", Path(root) / "commons" / "defaults.json"):
        try:
            k = (load_json(src, {}).get("knobs") or {}).get(programme)
        except Unreadable:
            k = None
        if k:
            return k
    return MAIN_KNOBS.get(programme)


def map_at_least(root, level):
    k = knob(root, "map")
    return k in MAP_LEVELS and MAP_LEVELS.index(k) >= MAP_LEVELS.index(level)


def domain_cfg(root):
    try:
        d = load_map(root, "dirs", required=False)
    except Unreadable:
        d = {}
    return {"exclude": d.get("exclude") or list(EXCLUDE_DEFAULT), "held": d.get("held") or list(HELD_DEFAULT)}


def classify(rel, cfg):
    for p in cfg["exclude"]:
        if rel == p.rstrip("/") or rel.startswith(p):
            return "excluded"
    for p in cfg["held"]:
        if rel == p.rstrip("/") or rel.startswith(p):
            return "held"
    return "domain"


def domain_files(root, cfg=None):
    """(domain, held, excluded) file lists: the walk every check counts against."""
    cfg = cfg or domain_cfg(root)
    out = {"domain": [], "held": [], "excluded": []}
    for f in tracked_files(root):
        out[classify(f, cfg)].append(f)
    return out["domain"], out["held"], out["excluded"]


def glob_match(path, pattern):
    """fnmatch on the full relative path; '**/' matches zero or more directories (the 2026-08-19 lesson)."""
    rx = ""
    i = 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            rx += "(?:.*/)?"
            i += 3
        elif pattern.startswith("**", i):
            rx += ".*"
            i += 2
        elif pattern[i] == "*":
            rx += "[^/]*"
            i += 1
        elif pattern[i] == "?":
            rx += "[^/]"
            i += 1
        else:
            rx += re.escape(pattern[i])
            i += 1
    return re.fullmatch(rx, path) is not None


def any_glob(path, patterns):
    return any(glob_match(path, p) for p in patterns)


def write_if_changed(path, text):
    p = Path(path)
    if p.exists() and p.read_text(encoding="utf-8") == text:
        return False
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")
    return True


def root_arg(argv):
    """--root DIR (default: the station this script lives in). Returns (root, argv without it)."""
    argv = list(argv)
    if "--root" in argv:
        i = argv.index("--root")
        if i + 1 >= len(argv):
            raise SystemExit(2)
        r = Path(argv[i + 1]).resolve()
        del argv[i:i + 2]
        return r, argv
    return ROOT, argv


def strip_comments(text, suffix):
    """Remove comments so a name mentioned only in a comment is never a trigger (MAP 3.6)."""
    if suffix == ".py":
        return "\n".join(re.sub(r"(^|\s)#.*$", r"\1", l) for l in text.splitlines())
    if suffix in (".js", ".mjs", ".ts"):
        text = re.sub(r"/\*.*?\*/", lambda m: "\n" * m.group(0).count("\n"), text, flags=re.S)
        return "\n".join(re.sub(r"(^|[^:])//.*$", r"\1", l) for l in text.splitlines())
    return text


def read_text(root, rel):
    try:
        return (Path(root) / rel).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None


def git_init_fixture(d):
    """A scratch repo with an explicit-path commit helper (no GIT_DIR exports; no `add -A`)."""
    git(d, "init", "-q", "-b", "main")
    return d


def commit_fixture(d, msg):
    r = git(d, "ls-files", "-o", "-m", "-d", "-z", "--exclude-standard")
    paths = [p for p in r.stdout.split("\0") if p]
    if paths:
        git(d, "add", "--", *paths)
    return git(d, "-c", "user.name=kit", "-c", "user.email=kit@localhost", "commit", "-q", "--allow-empty", "-m", msg)


def selftest():
    import tempfile
    ok = True

    def check(cond, msg):
        nonlocal ok
        if not cond:
            ok = False
            print("FAIL", msg)
    check(declares_generated('{\n "_generated_by": "x"}'), "json decl")
    check(declares_generated("<!-- GENERATED by tools/map/x.py -->"), "md decl")
    check(not declares_generated('"""docstring: this module writes the generated files"""'), "bare word")
    check(not declares_generated("a\nb\nc\nGENERATED by x"), "line 4 ignored")
    check(glob_match("tools/a/b/c.py", "tools/**/*.py") and glob_match("tools/c.py", "tools/**/*.py"), "** depth")
    check(not glob_match("tools/a/c.py", "tools/*.py"), "* is one segment")
    cfg = {"exclude": EXCLUDE_DEFAULT, "held": HELD_DEFAULT}
    check(classify("upstream/x~y/a.md", cfg) == "held" and classify(".upstream/a", cfg) == "excluded"
          and classify("tools/a.py", cfg) == "domain", "classify")
    with tempfile.TemporaryDirectory() as t:
        Path(t, "map").mkdir()
        Path(t, "map", "dirs.json").write_text('{"dirs": {"a": {"role": "x"}}, "exclude": [".git/"]}')
        Path(t, "map", "station_dirs.json").write_text('{"dirs": {"b": {"role": "y"}}}')
        d = load_map(t, "dirs")
        check(set(d["dirs"]) == {"a", "b"}, "overlay merge")
        check(knob(t, "map") == "L" and station_name(t) == "core", "main defaults")
        Path(t, "station.json").write_text('{"name": "s1", "knobs": {"map": "XS"}}')
        check(knob(t, "map") == "XS" and station_name(t) == "s1" and not map_at_least(t, "S"), "station knob")
        Path(t, "map", "tags.json").write_text("{broken")
        try:
            load_map(t, "tags")
            check(False, "corrupt json must raise")
        except Unreadable:
            pass
    print("selftest OK" if ok else "selftest FAILED")
    return 0 if ok else 1


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(selftest())
    print(__doc__.strip().splitlines()[0])
    sys.exit(2)
