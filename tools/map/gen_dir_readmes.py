#!/usr/bin/env python3
"""gen_dir_readmes.py — the directory registry (map/dirs.json + map/station_dirs.json) and its generated READMEs.

Earned by: lettuce `governance/dir.yml` (R18/R47: after a tree move many dirs had no README, so a reader could not
learn a dir's one job; READMEs are GENERATED so the role cannot drift from its single source) and L310 (a programme
marked CLOSED while its exit numbers failed: 18 root entries against <= 12 and 143 space-paths, with no check reporting
the second number; a rule needs a stated domain). Retires: lettuce TREE.yml `mapping:` (now `moved_from`).

`readme`: generated (rendered here) | hand (must carry `holds:` and `never holds:`) | none (the registry row is the
description; used for dirs whose files other slices own). Keys under an excluded or held prefix are refused, counted
and never written (the port of FORBIDDEN_PREFIXES: a generator never writes inside upstream material).
Gates (exit 1): DRIFT · UNREGISTERED (tracked dir at depth <= registry_depth) · ABSENT (unless optional) · HAND-SHAPE ·
ROOT (when root_ceiling is set). Worklist: PLACEMENT · SPACE · REFUSED.
CLI: --write | --check | --placement | --list-outputs | --selftest  [--root DIR]. Exit 0/1/2.
"""
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _common as C  # noqa: E402

TOOL = "tools/map/gen_dir_readmes.py"


def render(name, e):
    return "\n".join([
        "<!-- GENERATED by %s from map/dirs.json — edit dirs.json, not this file. -->" % TOOL,
        "owner: map/dirs.json · status: GENERATED · date: see git log · supersedes: none · audit: python3 %s --check" % TOOL,
        "", "# %s/" % name, "", e.get("role", ""), "",
        "**holds:** " + " · ".join(e.get("holds") or ["-"]), "",
        "**never holds:** " + " · ".join(e.get("never_holds") or ["-"]), ""] +
        (["moved from: " + ", ".join(e["moved_from"]), ""] if e.get("moved_from") else []))


def plan(root):
    reg = C.load_map(root, "dirs")
    cfg = C.domain_cfg(root)
    outs, refused = {}, []
    for name, e in sorted((reg.get("dirs") or {}).items()):
        if e.get("readme") != "generated":
            continue
        if C.classify(name.rstrip("/") + "/", cfg) != "domain":
            refused.append(name)
            continue
        if (Path(root) / name).is_dir() or not e.get("optional"):
            outs["%s/README.md" % name.rstrip("/")] = render(name.rstrip("/"), e)
    return reg, cfg, outs, refused


def check(root, placement_only=False):
    reg, cfg, outs, refused = plan(root)
    dirs = reg.get("dirs") or {}
    V, W = [], ["REFUSED %s: under an excluded/held prefix, never written" % r for r in refused]
    domain, held, excl = C.domain_files(root, cfg)
    depth = int(reg.get("registry_depth") or 1)
    tracked_dirs = set()
    for f in domain:
        parts = f.split("/")[:-1]
        for i in range(1, min(depth, len(parts)) + 1):
            tracked_dirs.add("/".join(parts[:i]))
    for rel, text in sorted(outs.items()):
        if C.read_text(root, rel) != text:
            V.append("DRIFT %s differs from its render (python3 %s --write)" % (rel, TOOL))
    for d in sorted(tracked_dirs - {k.rstrip("/") for k in dirs}):
        V.append("UNREGISTERED %s/: tracked dir with no map/dirs.json entry" % d)
    for k, e in sorted(dirs.items()):
        p = Path(root) / k
        if not p.is_dir() and not e.get("optional"):
            V.append("ABSENT %s/: registered but not on disk" % k)
        if e.get("readme") == "hand" and p.is_dir():
            t = (C.read_text(root, "%s/README.md" % k.rstrip("/")) or "").lower()
            if "holds:" not in t.replace("never holds:", "") or "never holds:" not in t:
                V.append("HAND-SHAPE %s/README.md lacks a holds: or never holds: line" % k)
    entries = [x for x in os.listdir(root) if x != ".git"]
    if reg.get("root_ceiling") is not None and len(entries) > int(reg["root_ceiling"]):
        V.append("ROOT %d root entries > ceiling %d" % (len(entries), reg["root_ceiling"]))
    P = []
    for rule in reg.get("placement") or []:
        for f in domain:
            if f.endswith(rule["ext"]) and not any(f.startswith(a) for a in rule["allowed_roots"]):
                P.append("PLACEMENT %s: %s outside %s" % (f, rule["ext"], ", ".join(rule["allowed_roots"])))
    P += ["SPACE %s" % f for f in domain if " " in f]
    if placement_only:
        return [], P, len(domain), (len(held), len(excl), len(entries))
    return V, W + P, len(dirs) + len(tracked_dirs), (len(held), len(excl), len(entries))


def selftest():
    import json
    import tempfile
    ok = True
    base = {"exclude": [".git/"], "registry_depth": 1, "root_ceiling": None, "placement": [{"ext": ".py", "allowed_roots": ["tools/"]}],
            "dirs": {"tools": {"role": "scripts", "holds": ["py"], "never_holds": ["data"], "readme": "generated"},
                     "docs": {"role": "docs", "readme": "hand"}, "map": {"role": "registries", "readme": "none"}, "upstream": {"role": "held", "readme": "generated", "optional": True}}}

    def mk(t, reg, files):
        Path(t, "map").mkdir(parents=True, exist_ok=True)
        Path(t, "map", "dirs.json").write_text(json.dumps(reg))
        for f, x in files.items():
            Path(t, f).parent.mkdir(parents=True, exist_ok=True)
            Path(t, f).write_text(x)
    clean = {"tools/a.py": "x", "docs/README.md": "holds: a\nnever holds: b\n", "upstream/x~y/f.md": "x"}
    cases = [("clean", base, clean, 0), ("drift", base, dict(clean, **{"tools/README.md": "hand edit"}), 1),
             ("unregistered", base, dict(clean, **{"misc/f.txt": "x"}), 1),
             ("absent", dict(base, dirs=dict(base["dirs"], gone={"role": "x"})), clean, 1),
             ("hand shape", base, dict(clean, **{"docs/README.md": "holds: a\n"}), 1),
             ("root ceiling", dict(base, root_ceiling=2), clean, 1)]
    for name, reg, files, want in cases:
        with tempfile.TemporaryDirectory() as t:
            mk(t, reg, files)
            if name != "drift":
                for rel, text in plan(t)[2].items():
                    Path(t, rel).write_text(text)
            V = check(t)[0]
            if (1 if V else 0) != want:
                ok = False
                print("FAIL", name, V)
            if Path(t, "upstream", "README.md").exists():
                ok = False
                print("FAIL upstream/README.md must never be written")
    with tempfile.TemporaryDirectory() as t:
        mk(t, base, dict(clean, **{"docs/x.py": "x"}))
        _, P, _, _ = check(t, placement_only=True)
        if not any(p.startswith("PLACEMENT docs/x.py") for p in P):
            ok = False
            print("FAIL placement worklist")
    print("selftest OK" if ok else "selftest FAILED")
    return 0 if ok else 1


def main(argv):
    root, argv = C.root_arg(argv)
    if "--selftest" in argv:
        return selftest()
    try:
        if "--list-outputs" in argv:
            print("\n".join(sorted(plan(root)[2])))
            return 0
        if "--write" in argv:
            n = sum(C.write_if_changed(Path(root) / rel, text) for rel, text in plan(root)[2].items())
            print("dirs: wrote %d README(s)" % n)
            return 0
        placement = "--placement" in argv
        V, W, d, (nh, nx, nroot) = check(root, placement)
    except C.Unreadable as e:
        print("%s: UNREADABLE %s" % ("placement" if "--placement" in argv else "dirs", e))
        return 2
    print(C.headline("placement" if placement else "dirs", len(V), len(W), d))
    print("domain: held %d file(s) and excluded %d file(s) counted separately · %d root entries" % (nh, nx, nroot))
    for x in V + W:
        print(x)
    return 1 if V else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
