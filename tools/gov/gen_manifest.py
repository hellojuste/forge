#!/usr/bin/env python3
"""gen_manifest.py -- commons/MANIFEST.json: the sha256 of every commons path (KIT_PLAN 3.3, DEC-core-0007).

owner: governance/rules.json R-branch-discipline
    python3 tools/gov/gen_manifest.py [--root DIR] --write | --check | --selftest
A commons path is every tracked (or untracked, not ignored) file that is NOT station-only (_gov.STATION_ONLY),
not the manifest itself, not an append-only union log (brain/*.jsonl) and not under a cache dir. A file whose
first 3 lines declare GENERATED is listed with "generated": true: both sides regenerate it, so commons_drift
checks its presence, not its bytes. Run --write on main; kit-root's assemble.py re-runs it at assembly.
commons_drift (gov_check.py) compares the working tree with this file, and this file with main's copy.
--check exits 1 when the committed manifest differs from a fresh render.
Earned by: KIT_PLAN 3.2 split fallback (J1 5.1, B 3.2): after `split.sh` a station repo has no main branch to
diff against, so the commons identity must travel as data.
"""
import argparse
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _gov  # noqa: E402

REL = "commons/MANIFEST.json"


def commons_paths(root):
    out = []
    for rel in _gov.tracked_files(root):
        if rel == REL or _gov.station_only(rel) or rel in _gov.APPEND_ONLY:
            continue
        if rel.split("/", 1)[0] in _gov.IGNORED_DIRS or "/__pycache__/" in "/" + rel:
            continue
        out.append(rel)
    return out


def render(root):
    files = {}
    for rel in commons_paths(root):
        p = Path(root) / rel
        try:
            head = p.read_text(encoding="utf-8", errors="replace")[:4000]
        except OSError:
            head = ""
        meta = {"sha256": _gov.sha256_file(p)}
        if _gov.declares_generated(head, root):
            meta["generated"] = True
        files[rel] = meta
    return {"_generated_by": "tools/gov/gen_manifest.py --write",
            "_why": "commons identity: every path identical on every branch (commons_drift). Generated files are presence-only.",
            "files": files}


def main(argv=None):
    _gov.setup_io()
    ap = argparse.ArgumentParser()
    ap.add_argument("--root")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args(argv)
    if a.selftest:
        return selftest()
    root = _gov.find_root(a.root)
    new = _gov.dump_json(render(root))
    p = Path(root) / REL
    if a.write:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(new, encoding="utf-8")
        print("gen_manifest: wrote %s (%d commons paths)" % (REL, len(render(root)["files"])))
        return 0
    if a.check:
        old = p.read_text(encoding="utf-8") if p.exists() else ""
        n = 0 if old == new else 1
        print(_gov.headline("gen_manifest", n, 0, 1))
        if n:
            print("  VIOLATION: %s is stale — python3 tools/gov/gen_manifest.py --write" % REL)
        return n
    sys.stdout.write(new)
    return 0


def selftest():
    fails, n = [], 0

    def ok(c, m):
        nonlocal n
        n += 1
        if not c:
            fails.append(m)

    with tempfile.TemporaryDirectory() as td:
        r = Path(td)
        _gov.write(r, "CLAUDE.md", "# x\n")
        _gov.write(r, "governance/OWNERSHIP.md", "<!-- GENERATED by tools/gov/gen_ownership.py -->\n# o\n")
        _gov.write(r, "station.json", "{}\n")
        _gov.write(r, "upstream/a~b/x.py", "x\n")
        _gov.write(r, ".claude/skills/pine/SKILL.md", "x\n")
        _gov.write(r, ".claude/skills/closeout/SKILL.md", "x\n")
        _gov.write(r, "brain/considered.jsonl", "{}\n")
        _gov.write(r, ".cache/audit/x.json", "{}\n")
        _gov.git(r, "init", "-q", "-b", "main")
        _gov.write(r, ".gitignore", ".cache/\n")
        files = render(r)["files"]
        ok(set(files) == {"CLAUDE.md", "governance/OWNERSHIP.md", ".claude/skills/closeout/SKILL.md", ".gitignore"},
           "commons set excludes station-only, union logs, caches: %s" % sorted(files))
        ok(files["governance/OWNERSHIP.md"].get("generated") is True and "generated" not in files["CLAUDE.md"],
           "GENERATED files are flagged")
        ok(main(["--root", td, "--check"]) == 1, "--check red before --write")
        ok(main(["--root", td, "--write"]) == 0 and main(["--root", td, "--check"]) == 0, "--write then --check green")
        _gov.write(r, "CLAUDE.md", "# changed\n")
        ok(main(["--root", td, "--check"]) == 1, "--check red after a commons edit")
        ok(_gov.declares_generated((r / REL).read_text(), r), "the manifest declares itself GENERATED")
    if fails:
        print("selftest FAILED (%d of %d cases)" % (len(fails), n))
        for f in fails:
            print(" - " + f)
        return 1
    print("selftest OK (%d cases)" % n)
    return 0


if __name__ == "__main__":
    sys.exit(main())
