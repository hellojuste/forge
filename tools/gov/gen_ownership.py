#!/usr/bin/env python3
"""gen_ownership.py -- render governance/OWNERSHIP.md from governance/rules.json + rules.d/*.json (GOV 3.4).

owner: governance/rules.json R-ownership
    python3 tools/gov/gen_ownership.py [--root DIR] --write | --check | --selftest
ONE registry (rules.json) and one generated human table, because lettuce kept the owner table and the
rule->hook inventory apart and they drifted ("listed six and drifted", hooks Table A row 29).
--check exits 1 when OWNERSHIP.md differs from a fresh render. No date in the output: the render is a
pure function of the registry, so --check never goes stale by the calendar.
Earned by: lettuce governance/ownership.md + tools/hooks/README.md Tables A/B drift (PROGRAMME_GOVERNANCE 3.4).
"""
import argparse
import json
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _gov  # noqa: E402

REL = "governance/OWNERSHIP.md"
THREE_RULES = '''**The three rules of ownership** (carried verbatim from lettuce `governance/ownership.md`, operator 2026-09-11 §§1, 2, 5; the file names are lettuce's — here the state document is the station's plan, the record is `governance/HISTORY.md`, the owed list is `governance/DEFECTS.md` + the ledger's OWED rows):

1. **One owner.** *"A rule has exactly one owner. A skill that repeats an owner's rule is a pointer: 'see `<owner> §N`.' A skill that needs to extend a rule adds a named subsection and cites the owner's id. A skill that copies a rule is a defect — filed as an L-row in the same commit as the fix."*
2. **State versus history.** *"`PLAN.md` states current state and forward work. `PLAN_RECORD.md` states everything that has been superseded. A recovery point goes to the RECORD, not to the Plan; the Plan carries only the ONE NEXT STEP that came out of it."*
3. **One debt list.** *"A list of owed rows belongs in ONE place. New owed items are added to `PLAN.md` §03; nothing else in the Plan maintains a register-debt list."*
'''


def _enf(row):
    e = _gov.norm_enforcement(row.get("enforcement") or {})
    if e["kind"] == "hook":
        return "HOOKED `%s` (%s)" % (e["ref"], (row.get("enforcement") or {}).get("verdict", "report"))
    if e["kind"] == "check":
        return "CHECK `%s`" % e["ref"]
    if e["kind"] == "owed":
        return "OWED %s — trigger: %s" % (e["shape"], e["trigger"])
    if e["kind"] == "not-hookable":
        return "NOT HOOKABLE: %s" % e["why"]
    return "?"


def _cell(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def render(root):
    rows = _gov.load_rows(root, "governance/rules.json", "governance/rules.d", "rules")
    out = ["<!-- GENERATED by tools/gov/gen_ownership.py from governance/rules.json + governance/rules.d/*.json — DO NOT EDIT; regenerate with --write -->",
           "# OWNERSHIP — one owner per rule",
           "owner: governance/rules.json · status: GENERATED · date: see git log · supersedes: none · audit: python3 tools/gov/gen_ownership.py --check",
           "",
           "Every rule has ONE owner; every other place that mentions it is a pointer. Answer \"what owns X\" here, not with a grep (CLAUDE.md § Token sinks).",
           "",
           "| id | rule | OWNER | enforced by | rung | upstream | every other occurrence is |",
           "|---|---|---|---|---|---|---|"]
    for r in sorted(rows, key=lambda x: (x.get("_src") != "governance/rules.json", x.get("_src"), x.get("id", ""))):
        ptr = ", ".join("`%s`" % p for p in r.get("pointers") or []) or "—"
        src = "" if r.get("_src") == "governance/rules.json" else " (%s)" % r.get("_src")
        out.append("| %s%s | %s | `%s` | %s | %s | %s | %s |" % (
            _cell(r.get("id")), _cell(src), _cell(r.get("headline")), _cell(r.get("owner")), _cell(_enf(r)),
            _cell(r.get("rung")), _cell(r.get("upstream", "")), _cell(ptr)))
    canon = {}
    for p in [Path(root) / "governance" / "rules.json"] + _gov.fragments(root, "governance/rules.d"):
        if p.exists():
            canon.update(_gov.load_json(p).get("canon") or {})
    out += ["", "**CANON groups** (gov_check.py canon): " + (", ".join("`%s` (%s)" % kv for kv in sorted(canon.items())) or "none declared"), "", THREE_RULES]
    return "\n".join(out).rstrip() + "\n"


def main(argv=None):
    _gov.setup_io()
    ap = argparse.ArgumentParser()
    ap.add_argument("--root")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args(argv)
    if a.selftest:
        return selftest()
    root = _gov.find_root(a.root)
    try:
        new = render(root)
    except _gov.GovError as e:
        print("gen_ownership: UNREADABLE (%s)" % e)
        return 2
    p = Path(root) / REL
    if a.write:
        p.write_text(new, encoding="utf-8")
        print("gen_ownership: wrote %s" % REL)
        return 0
    if a.check:
        old = p.read_text(encoding="utf-8") if p.exists() else ""
        n = 0 if old == new else 1
        print(_gov.headline("gen_ownership", n, 0, 1))
        if n:
            print("  VIOLATION: %s drifted from rules.json — python3 tools/gov/gen_ownership.py --write" % REL)
        return n
    sys.stdout.write(new)
    return 0


def selftest():
    fails, n = [], 0

    def ok(c, m):
        nonlocal n
        n += 1
        if not c:
            fails.append(m)

    with tempfile.TemporaryDirectory() as td:
        r = Path(td)
        row = {"id": "R-a", "headline": "a | rule", "owner": "CLAUDE.md#Invariants", "pointers": [],
               "enforcement": {"kind": "hook", "ref": ".claude/hooks/x.py", "verdict": "deny"}, "rung": "hard",
               "upstream": "NEVER", "earned_by": "x"}
        _gov.write(r, "governance/rules.json", json.dumps({"rules": [row], "canon": {"g": "strict"}}))
        _gov.write(r, "governance/rules.d/map.json", json.dumps({"rules": [dict(row, id="R-map")]}))
        t = render(r)
        ok(_gov.declares_generated(t), "line 1 declares GENERATED")
        ok("R-map" in t and "(governance/rules.d/map.json)" in t, "fragments rendered with their source")
        ok("a \\| rule" in t, "pipes escaped")
        ok(_gov.five_field_header(t)["ok"], "five-field header")
        ok(main(["--root", td, "--check"]) == 1, "--check red when absent")
        main(["--root", td, "--write"])
        ok(main(["--root", td, "--check"]) == 0, "--check green after --write")
        _gov.write(r, "governance/rules.json", json.dumps({"rules": [dict(row, headline="changed")]}))
        ok(main(["--root", td, "--check"]) == 1, "--check red on drift")
    if fails:
        print("selftest FAILED (%d of %d cases)" % (len(fails), n))
        for f in fails:
            print(" - " + f)
        return 1
    print("selftest OK (%d cases)" % n)
    return 0


if __name__ == "__main__":
    sys.exit(main())
