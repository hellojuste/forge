#!/usr/bin/env python3
"""carry_design.py -- the lean lessons and the three programme specs the commons cites, shipped as data under docs/design/.

Earned by: LEAN review F3 (2026-10-16): hooks, rules and brain nodes justify themselves with LL-01 ... LL-51 and cite
`_design/LEAN_LESSONS.md`, a file that was never shipped, so a fresh Claude could open none of them. ORDER 2 (verbatim:
"pls dont ignore my instruction to backfill the efficiency programmes we have ... inclusive of the mapping and brains
and governance") is why the programme specs travel with the lessons.

The four files are carried VERBATIM (their lettuce paths are evidence, not instructions) with one GENERATED header
line naming the source, so the hedge words they quote are judged at the source (deny_noted_defect skips GENERATED
files) and a hand edit is refused (deny_generated_edit). The source is the design branch the kit was planned on; in a
private copy without that branch, --check still proves the LL ids resolve and says the byte comparison was skipped.

CLI: carry_design.py [--write | --check] [--root <dir>] [--ref <git ref>] [--selftest]
  --write  copy <ref>:design/<NAME>.md -> docs/design/<NAME>.md with the header (needs the ref).
  --check  (default) (1) every docs/design/<NAME>.md exists with its header; (2) when the ref is reachable, its body
           equals the source byte for byte; (3) every `LL-nn` cited in a tracked file resolves to a `### LL-nn` heading
           in docs/design/LEAN_LESSONS.md.
Exit: 0 clean . 1 violation . 2 unreadable.
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

NAMES = ("LEAN_LESSONS", "PROGRAMME_MAPPING", "PROGRAMME_BRAIN", "PROGRAMME_GOVERNANCE")
DEST = "docs/design"
LANES = ("upstream/", "repertoire/", "study/", "nc-lane/", ".upstream/")  # upstream text is data, never a citation
REF = "origin/claude/stable-kit-design"
HEADER = "<!-- GENERATED by tools/gov/carry_design.py from %s:design/%s.md — carried verbatim as data; do not edit, regenerate -->\n"
LL_RE = re.compile(r"\bLL-(\d{2})\b")
HEAD_RE = re.compile(r"^### LL-(\d{2})\b", re.M)


def _git(root, *a):
    return subprocess.run(["git", "-C", str(root)] + list(a), capture_output=True, text=True)


def source(root, ref, name):
    r = _git(root, "show", "%s:design/%s.md" % (ref, name))
    return r.stdout if r.returncode == 0 else None


def render(ref, name, body):
    return HEADER % (ref, name) + body


def body_of(text):
    first, _, rest = text.partition("\n")
    return rest if first.startswith("<!-- GENERATED by tools/gov/carry_design.py") else None


def write(root, ref):
    n = 0
    for name in NAMES:
        src = source(root, ref, name)
        if src is None:
            print("carry_design: %s:design/%s.md unreachable (git fetch origin %s)" % (ref, name, ref.split("/", 1)[-1]))
            return 2
        p = Path(root) / DEST / (name + ".md")
        p.parent.mkdir(parents=True, exist_ok=True)
        new = render(ref, name, src)
        if not p.exists() or p.read_text(encoding="utf-8") != new:
            p.write_text(new, encoding="utf-8")
            n += 1
    print("carry_design: %d of %d written under %s/" % (n, len(NAMES), DEST))
    return 0


def tracked(root):
    r = _git(root, "ls-files", "-z")
    return [f for f in r.stdout.split("\0") if f] if r.returncode == 0 else []


def check(root, ref):
    root = Path(root)
    viol, notes, compared = [], [], 0
    for name in NAMES:
        p = root / DEST / (name + ".md")
        if not p.exists():
            viol.append("%s/%s.md missing (python3 tools/gov/carry_design.py --write)" % (DEST, name))
            continue
        body = body_of(p.read_text(encoding="utf-8"))
        if body is None:
            viol.append("%s/%s.md: no GENERATED header line" % (DEST, name))
            continue
        src = source(root, ref, name)
        if src is None:
            notes.append("source %s unreachable: byte comparison skipped for %s" % (ref, name))
        elif src != body:
            viol.append("%s/%s.md differs from %s:design/%s.md (regenerate with --write)" % (DEST, name, ref, name))
        else:
            compared += 1
    lessons = root / DEST / "LEAN_LESSONS.md"
    have = set(HEAD_RE.findall(lessons.read_text(encoding="utf-8"))) if lessons.exists() else set()
    cited = {}
    for f in tracked(root):
        if f.startswith((DEST + "/",) + LANES) or not f.endswith((".md", ".py", ".json", ".js", ".tmpl")):
            continue
        try:
            text = (root / f).read_text(encoding="utf-8", errors="replace")
        except (OSError, IsADirectoryError):
            continue
        for m in LL_RE.findall(text):
            cited.setdefault(m, f)
    for ll, f in sorted(cited.items()):
        if ll not in have:
            viol.append("LL-%s (cited in %s) resolves to no '### LL-%s' heading in %s/LEAN_LESSONS.md" % (ll, f, ll, DEST))
    print("design_docs: %d violation(s) · %d worklist · denominator %d" % (len(viol), len(notes), len(NAMES) + len(cited)))
    for v in viol:
        print("  VIOLATION: " + v)
    for n in notes:
        print("  WORKLIST: " + n)
    print("  %d LL id(s) cited, all resolving to docs/design/LEAN_LESSONS.md; %d of %d files byte-compared with the source"
          % (len(cited), compared, len(NAMES)) if not viol else "")
    return 1 if viol else 0


def selftest():
    import tempfile
    cases = 0
    with tempfile.TemporaryDirectory() as t:
        g = ["git", "-C", t, "-c", "user.name=k", "-c", "user.email=k@l"]
        subprocess.run(["git", "init", "-q", "-b", "main", t], check=True)
        (Path(t) / "design").mkdir()
        for n in NAMES:
            (Path(t) / "design" / (n + ".md")).write_text("# %s\n### LL-01 · one\n### LL-02 · two\nthe lettuce path was noted\n" % n)
        subprocess.run(g + ["add", "design"], check=True)
        subprocess.run(g + ["commit", "-qm", "d"], check=True)
        subprocess.run(g + ["branch", "design-ref"], check=True)
        assert check(t, "design-ref") == 1, "missing docs are violations"
        cases += 1
        assert write(t, "design-ref") == 0 and check(t, "design-ref") == 0, "write then check clean"
        cases += 1
        assert (Path(t) / DEST / "LEAN_LESSONS.md").read_text().startswith("<!-- GENERATED by tools/gov/carry_design.py"), "header"
        cases += 1
        (Path(t) / "hook.py").write_text("# LL-02 and LL-07\n")
        subprocess.run(g + ["add", "hook.py"], check=True)
        assert check(t, "design-ref") == 1, "an unresolved LL id is a violation"
        cases += 1
        (Path(t) / "hook.py").write_text("# LL-02\n")
        p = Path(t) / DEST / "PROGRAMME_BRAIN.md"
        p.write_text(p.read_text() + "edited\n")
        assert check(t, "design-ref") == 1, "a hand edit differs from the source"
        cases += 1
        write(t, "design-ref")
        assert check(t, "no-such-ref") == 0, "an absent source ref skips the byte comparison, still checks LL ids"
        cases += 1
    print("carry_design selftest OK (%d cases)" % cases)
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--root", default=".")
    ap.add_argument("--ref", default=REF)
    a = ap.parse_args(argv)
    if a.selftest:
        return selftest()
    return write(a.root, a.ref) if a.write else check(a.root, a.ref)


if __name__ == "__main__":
    sys.exit(main())
