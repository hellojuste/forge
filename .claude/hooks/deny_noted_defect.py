#!/usr/bin/env python3
"""deny_noted_defect.py -- PreToolUse Bash DENY on `git commit`: "noted" is not an outcome (GOV 3.16, LEAN LL-31).

owner: governance/rules.json R-defects (CLAUDE.md invariant 6)
On a `git commit` statement (found by _cmdscan, so a quoted mention is not a commit) it reads the staged diff
(`git diff --cached -U0`) of the files matching gov.defect_watch and denies when an ADDED line matches
gov.hedge_regex (case-insensitive) and carries no register id (DEF-/L-/DEC-[<station>-]nnnn or #<n>).
While MERGE_HEAD exists, a line already present in that file at MERGE_HEAD is not counted (a merge's
--cached diff is against the first parent only; the line was committed on the other side).
Earned by: lettuce Invariant 14 ("thats like me writing damn that sql is rough af and then doing nothing"),
AMENDED 2026-10-09 after a child lane left its own TRI_ASC/TRI_DSC defect as "out of scope".
Release: put the register id on the line (fix it, or file DEF-nnnn with `python3 tools/gov/new_row.py def`),
or a governance/RELEASES.json row with scope deny_noted_defect on the protected branch.
Fails OPEN: if the staged diff cannot be read it allows and says so in one report line.
"""
import json
import os
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import _cmdscan  # noqa: E402

SCOPE = "deny_noted_defect"
ID_RE = re.compile(r"\b(?:DEF|L|DEC)-(?:[a-z][a-z0-9-]*-)?\d{4}\b|#\d+")
DEFAULT_HEDGE = r"not mine|pre-existing|unexplained|not explained|(?<![\w-])noted(?![\w-])|for the next author|presumed|TODO later"
GEN_RE = re.compile(r'GENERATED by \S+|GENERATED\W+(?:do not edit|never hand-edit|regenerat)|"_generated_by"\s*:', re.I)
DEFAULT_WATCH = ["governance/*.md", "docs/**/*.md", ".summon/returns/*.json"]


def _gov(root):
    g = {}
    for rel in ("commons/defaults.json", "station.json"):
        try:
            g.update(json.loads((Path(root) / rel).read_text(encoding="utf-8")).get("gov") or {})
        except (OSError, ValueError):
            pass
    return g


def _git(d, *a):
    return subprocess.run(["git", "-C", str(d), *a], capture_output=True, text=True, errors="replace")


def hedges(repo, watch, hedge_rx):
    """[(file, line)] staged added lines that hedge without a register id. Raises RuntimeError if unreadable."""
    specs = [":(glob)" + w for w in watch]
    r = _git(repo, "diff", "--cached", "-U0", "--no-color", "--", *specs)
    if r.returncode != 0:
        raise RuntimeError("git diff --cached failed: %s" % r.stderr.strip()[:120])
    merge = _git(repo, "rev-parse", "-q", "--verify", "MERGE_HEAD")
    merge_head = merge.stdout.strip() if merge.returncode == 0 else None
    other_cache, gen_cache = {}, {}
    out, cur = [], None
    for line in r.stdout.splitlines():
        if line.startswith("+++ "):
            cur = line[6:] if line.startswith("+++ b/") else None
            continue
        if not cur or not line.startswith("+") or line.startswith("+++"):
            continue
        if cur not in gen_cache:  # a GENERATED file restates its sources; the hedge is judged at the source
            head = _git(repo, "show", ":%s" % cur).stdout.splitlines()[:3]
            gen_cache[cur] = any(GEN_RE.search(h) for h in head)
        if gen_cache[cur]:
            continue
        text = line[1:]
        if not hedge_rx.search(text) or ID_RE.search(text):
            continue
        if merge_head:
            if cur not in other_cache:
                s = _git(repo, "show", "%s:%s" % (merge_head, cur))
                other_cache[cur] = set(s.stdout.splitlines()) if s.returncode == 0 else set()
            if text in other_cache[cur]:
                continue
        out.append((cur, text.strip()))
    return out


def main():
    try:
        payload = json.loads(sys.stdin.read() or "{}")
    except ValueError:
        return 0
    cmd = (payload.get("tool_input") or {}).get("command") or ""
    commits = [(d, a) for d, sub, a in _cmdscan.git_calls(cmd) if sub == "commit"]
    if not commits:
        return 0
    root = os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd()
    g = _gov(root)
    try:
        rx = re.compile(g.get("hedge_regex") or DEFAULT_HEDGE, re.I)
        found = []
        for d, _ in commits:
            repo = Path(payload.get("cwd") or os.getcwd()) / (d or "")
            found += hedges(repo, g.get("defect_watch") or DEFAULT_WATCH, rx)
    except Exception as e:
        import _report
        _report.report("PreToolUse", "deny_noted_defect: cannot read the staged diff (%s); allowed, fail-open" % e,
                       payload=payload, root=root)
        return 0
    if not found:
        return 0
    try:
        import _release
        if _release.covers(SCOPE, cmd, root=root):
            return 0
    except Exception:
        pass
    f, t = found[0]
    more = (" (+%d more)" % (len(found) - 1)) if len(found) > 1 else ""
    sys.stderr.write('DENY-NOTED-DEFECT: %s: "%s" hedges with no register id%s — release: fix it, or file DEF-nnnn '
                     '(python3 tools/gov/new_row.py def "<subject>") and put the id on the line (CLAUDE.md invariant 6)\n'
                     % (f, t[:140], more))
    return 2


def selftest():
    import tempfile
    fails, n = [], 0

    def ok(c, m):
        nonlocal n
        n += 1
        if not c:
            fails.append(m)

    def hook(repo, cmd):
        p = subprocess.run([sys.executable, str(Path(__file__).resolve())], cwd=str(repo), capture_output=True, text=True,
                           input=json.dumps({"tool_name": "Bash", "tool_input": {"command": cmd}, "cwd": str(repo), "session_id": "st"}),
                           env=dict(os.environ, CLAUDE_PROJECT_DIR=str(repo)))
        return p.returncode, p.stderr

    with tempfile.TemporaryDirectory() as td:
        r = Path(td)
        g = lambda *a: subprocess.run(["git", "-C", td, *a], capture_output=True, text=True)
        cm = lambda m: g("-c", "user.name=k", "-c", "user.email=k@l", "commit", "-qm", m)
        g("init", "-q", "-b", "main")
        (r / "governance").mkdir()
        (r / "governance" / "NOTES.md").write_text("# notes\n")
        (r / "src.md").write_text("x\n")
        g("add", "--", "governance/NOTES.md", "src.md")
        cm("base")
        (r / "governance" / "NOTES.md").write_text("# notes\n- pre-existing bug in x\n")
        g("add", "--", "governance/NOTES.md")
        rc, err = hook(r, "git commit -m 'work'")
        ok(rc == 2 and err.startswith("DENY-NOTED-DEFECT") and "release:" in err, "hedge in watched file denied: %s %r" % (rc, err))
        rc, _ = hook(r, "cd . && git commit -m w")
        ok(rc == 2, "chained commit denied")
        rc, _ = hook(r, "echo 'git commit -m x'")
        ok(rc == 0, "quoted mention is not a commit")
        rc, _ = hook(r, "git status")
        ok(rc == 0, "not a commit")
        (r / "governance" / "NOTES.md").write_text("# notes\n- pre-existing bug in x, filed DEF-0004\n")
        g("add", "--", "governance/NOTES.md")
        rc, _ = hook(r, "git commit -m w")
        ok(rc == 0, "line with DEF-0004 allowed")
        (r / "governance" / "NOTES.md").write_text("# notes\n- noted for later, DEF-markets-0002\n")
        g("add", "--", "governance/NOTES.md")
        ok(hook(r, "git commit -m w")[0] == 0, "station-prefixed id allowed")
        (r / "governance" / "NOTES.md").write_text("# notes\n- R-noted-defect and deny_noted_defect are names, not hedges\n")
        g("add", "--", "governance/NOTES.md")
        ok(hook(r, "git commit -m w")[0] == 0, "an identifier containing 'noted' is not a hedge")
        (r / "governance" / "GEN.md").write_text("<!-- GENERATED by tools/x.py -->\n- pre-existing bug restated\n")
        g("add", "--", "governance/GEN.md")
        ok(hook(r, "git commit -m w")[0] == 0, "a GENERATED file is judged at its source")
        g("reset", "-q")
        (r / "governance" / "GEN.md").unlink()
        (r / "governance" / "NOTES.md").write_text("# notes\n")
        (r / "src.md").write_text("x\n- pre-existing bug in x\n")
        g("add", "--", "src.md")
        ok(hook(r, "git commit -m w")[0] == 0, "unwatched file allowed")
        g("reset", "-q")
        (r / "src.md").write_text("x\n")
        # merge of a branch carrying the line
        g("switch", "-q", "-c", "side")
        (r / "governance" / "NOTES.md").write_text("# notes\n- presumed flaky, see thread\n")
        g("add", "--", "governance/NOTES.md")
        cm("side")
        g("switch", "-q", "main")
        (r / "src.md").write_text("main change\n")
        g("add", "--", "src.md")
        cm("main")
        g("merge", "--no-commit", "--no-ff", "side")
        ok((r / ".git" / "MERGE_HEAD").exists(), "fixture merge in progress")
        rc, err = hook(r, "git commit -m merge")
        ok(rc == 0, "merge carrying an already-committed line allowed: %s %r" % (rc, err))
        # fail open outside a repo
        with tempfile.TemporaryDirectory() as nd:
            rc, _ = hook(Path(nd), "git commit -m x")
            ok(rc == 0, "unreadable diff fails open")
    if fails:
        print("selftest FAILED (%d of %d cases)" % (len(fails), n))
        for f in fails:
            print(" - " + f)
        return 1
    print("selftest OK (%d cases)" % n)
    return 0


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(selftest())
    sys.exit(main())
